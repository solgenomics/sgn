sub prepare : Path('/ajax/script_factory/prepare') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);

    my $dataset_id = $c->req->param('dataset_id');
    if (!$dataset_id || $dataset_id !~ /^\d+$/) {
        $c->stash->{rest} = { error => 'Please select a dataset.' };
        return;
    }

    my ($schema, $people_schema) = _schemas($c);
    my $dir = _work_dir($c);
    my ($fh, $tempfile) = tempfile("sf_XXXXXXXX", DIR => $dir);
    close($fh);
    my $token = basename($tempfile);
    my $pheno_file = "$tempfile.phenotype.txt";

    my ($ds, $traits_in_ds);
    try {
        $ds = CXGN::Dataset::File->new(
            people_schema => $people_schema,
            schema => $schema,
            sp_dataset_id => $dataset_id,
            # All values are loaded: outliers are handled in step 2 (rules, values
            # excluded by hand, dataset / database marks shown per value), so a value
            # is never dropped before the user sees it, and never as a whole plot.
            exclude_dataset_outliers => 0,
            exclude_phenotype_outlier => 0,
            file_name => $tempfile,
            quotes => 0,
        );
        $traits_in_ds = $ds->retrieve_traits();
    } catch {
        $c->stash->{rest} = { error => "Could not open the dataset: $_" };
    };
    return if $c->stash->{rest};

    # Breedbase reads datasets from the phenotype search cache (materialized
    # views), which on a large database can be hours behind new uploads. When
    # the cache does not hold every value of the dataset's trials, the dataset
    # is read from the database tables instead, so the summary and the
    # analysis always use all of its data.
    my $cache = try { _phenotype_cache_check($schema, $ds, $traits_in_ds) }
                catch { print STDERR "Analysis Pipeline: phenotype cache of dataset $dataset_id not checked: $_\n"; undef };
    my $source = ($cache && @{$cache->{stale}}) ? 'database' : 'cache';
    try {
        if ($source eq 'database') {
            _write_native_phenotypes($schema, $ds, $traits_in_ds, $pheno_file);
        } else {
            $ds->retrieve_phenotypes($pheno_file);
        }
    } catch {
        $c->stash->{rest} = { error => "Could not retrieve the dataset phenotypes: $_" };
    };
    return if $c->stash->{rest};

    if (!-s $pheno_file) {
        $c->stash->{rest} = { error => 'The dataset has no phenotypes. Please choose a dataset with trials and traits.' };
        return;
    }

    my ($keys, $idx, $rows) = _read_pheno_file($pheno_file);

    # treatments are not traits: management factor columns come after 'notes',
    # treatment variables belong to the experiment treatment ontologies
    my $notes_i = $idx->{notes};
    my @legacy_trt_cols = defined($notes_i) ? @$keys[ $notes_i + 1 .. $#$keys ] : ();
    my %is_treatment = map { $_ => 1 } (@legacy_trt_cols, grep { /\|(EXPERIMENT_TREATMENT|COMP_EXP_TREATMENT):/ } @$keys);

    my %trait_names = map { $_->[1] => 1 } @{$traits_in_ds || []};
    my @trait_cols = grep { exists($trait_names{$_}) && !$is_treatment{$_} } @$keys;
    if (!@trait_cols) {
        # fall back to the columns after the seedlot block of the file
        my $start = $idx->{availableGermplasmSeedlotUniquenames};
        @trait_cols = grep { $_ ne 'notes' && !$is_treatment{$_} } @$keys[ ($start // $#$keys) + 1 .. $#$keys ] if defined $start;
    }

    my $level_i = $idx->{observationLevel};
    my @plot_rows = grep { !defined($level_i) || !defined($_->[$level_i]) || $_->[$level_i] eq '' || lc($_->[$level_i]) eq 'plot' } @$rows;
    my $treatments = _treatment_factors($c, $keys, $idx, \@plot_rows, \@legacy_trt_cols, [ grep { $is_treatment{$_} } @$keys ]);

    my @traits;
    foreach my $t (@trait_cols) {
        my $i = $idx->{$t};
        my ($n, $sum, $min, $max) = (0, 0, undef, undef);
        foreach my $r (@plot_rows) {
            my $v = $r->[$i];
            next if !_is_number($v);
            $n++; $sum += $v;
            $min = $v if !defined($min) || $v < $min;
            $max = $v if !defined($max) || $v > $max;
        }
        next if $n == 0;
        push @traits, { name => $t, short => _short_trait($t), n => $n, mean => $sum / $n, min => $min, max => $max };
    }

    my %trials;
    my %accessions;
    my %programs;
    my $col = sub { my ($r, $name) = @_; my $i = $idx->{$name}; return defined($i) ? $r->[$i] : undef; };
    foreach my $r (@plot_rows) {
        my $trial = $col->($r, 'studyName') // 'unknown';
        my $t = $trials{$trial} ||= {
            trial => $trial,
            trial_id => $col->($r, 'studyDbId'),
            location => $col->($r, 'locationName'),
            year => $col->($r, 'studyYear'),
            design => $col->($r, 'studyDesign'),
            n_plots => 0, acc => {}, rep => {}, block => {}, row => {}, col => {}, rc => 0,
        };
        $t->{n_plots}++;
        my $acc = $col->($r, 'germplasmName');
        $t->{acc}->{$acc}++ if defined $acc;
        $t->{n_checks}++ if lc($col->($r, 'entryType') // '') =~ /^(check|checks|control)$/;
        my $prog_id = $col->($r, 'programDbId');
        if (defined($prog_id) && $prog_id =~ /^\d+$/) {
            $programs{$prog_id} ||= { id => $prog_id, name => $col->($r, 'programName'), n_plots => 0 };
            $programs{$prog_id}->{n_plots}++;
        }
        $accessions{$acc} = 1 if defined $acc;
        foreach my $f (['rep', 'replicate'], ['block', 'blockNumber'], ['row', 'rowNumber'], ['col', 'colNumber']) {
            my $v = $col->($r, $f->[1]);
            $t->{$f->[0]}->{$v} = 1 if defined($v) && $v ne '';
        }
        my ($rv, $cv) = ($col->($r, 'rowNumber'), $col->($r, 'colNumber'));
        $t->{rc}++ if _is_number($rv) && _is_number($cv);
        push @{$t->{plots}}, {
            acc => $acc, rep => $col->($r, 'replicate'), block => $col->($r, 'blockNumber'),
            row => (_is_number($rv) ? $rv : undef), col => (_is_number($cv) ? $cv : undef),
            check => (lc($col->($r, 'entryType') // '') =~ /^(check|checks|control)$/ ? 1 : 0),
        };
    }

    my @trials;
    foreach my $name (sort keys %trials) {
        my $t = $trials{$name};
        my $n_acc = scalar(keys %{$t->{acc}});
        my $replicated = grep { $_ > 1 } values %{$t->{acc}};
        my $has_rowcol = ($t->{rc} >= 0.9 * $t->{n_plots} && keys(%{$t->{row}}) > 1 && keys(%{$t->{col}}) > 1) ? 1 : 0;
        push @trials, {
            trial => $name,
            trial_id => $t->{trial_id},
            location => $t->{location},
            year => $t->{year},
            design => $t->{design},
            n_plots => $t->{n_plots},
            n_accessions => $n_acc,
            n_reps => scalar(keys %{$t->{rep}}),
            n_blocks => scalar(keys %{$t->{block}}),
            n_rows => scalar(keys %{$t->{row}}),
            n_cols => scalar(keys %{$t->{col}}),
            has_rowcol => $has_rowcol,
            replicated => $replicated ? 1 : 0,
            n_check_plots => $t->{n_checks} // 0,
            support => _factor_support($t->{plots} || []),
        };
    }

    my $pedigree = try { _write_pedigree($schema, [ sort keys %accessions ], "$tempfile.pedigree.txt") }
                   catch { { n_with_parents => 0, error => "$_" } };

    my %locations = map { ($_->{location} // '') => 1 } @trials;
    my %years = map { ($_->{year} // '') => 1 } @trials;

    # values marked as outliers in Breedbase: step 2 starts with them excluded
    # (only the marked value, never the whole plot)
    my %unit_info;
    foreach my $r (@plot_rows) {
        my $unit = $col->($r, 'observationUnitName');
        $unit_info{$unit} = [ $col->($r, 'studyName'), $col->($r, 'germplasmName') ] if defined $unit;
    }
    my $marked = try { _marked_outliers($schema, $ds, [ map { $_->{name} } @traits ], \%unit_info) }
                 catch { print STDERR "Analysis Pipeline: marked outliers of dataset $dataset_id not read: $_\n"; [] };
    # genotyping protocols with genotypes of the dataset's accessions (G and H models)
    my $genotyping = try { _genotyping_protocols($schema, [ map { $_->[0] } @{ $ds->retrieve_accessions() || [] } ]) }
                     catch { print STDERR "Analysis Pipeline: genotyping protocols of dataset $dataset_id not read: $_\n"; [] };
    # traits measured more than once per plot (all measurements to <token>.repeated.txt)
    my $repeated = try { _repeated_measurements($schema, $ds, [ map { $_->{name} } @traits ], \%unit_info, "$tempfile.repeated.txt") }
                   catch { print STDERR "Analysis Pipeline: repeated measurements of dataset $dataset_id not read: $_\n"; [] };

    $c->stash->{rest} = {
        token => $token,
        dataset_id => $dataset_id,
        dataset_name => $ds->name(),
        dataset_is_owner => (($ds->sp_person_id() // -1) == _user_id($c)) ? 1 : 0,
        dataset_n_outliers => scalar(@{ $ds->outliers() || [] }),
        marked_outliers => $marked,
        repeated => $repeated,
        genotyping_protocols => $genotyping,
        phenotype_file => $pheno_file,    # archived as training data when the analysis is stored
        traits => \@traits,
        trials => \@trials,
        n_plots => scalar(@plot_rows),
        n_accessions => scalar(keys %accessions),
        n_locations => scalar(keys %locations),
        n_years => scalar(keys %years),
        # where the phenotypes were read from: 'cache' (search cache, up to date)
        # or 'database' (tables, because the cache missed values of stale_trials)
        phenotype_source => $source,
        stale_trials => $cache ? $cache->{stale} : [],
        pedigree => $pedigree,
        treatments => $treatments,
        treatment_types => _treatment_types($c),
        # breeding programs of the trials, most plots first (default program of a stored analysis)
        programs => [ sort { $b->{n_plots} <=> $a->{n_plots} } values %programs ],
    };
}

sub plot_data : Path('/ajax/script_factory/plot_data') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);

    my $token = $c->req->param('token');
    my $traits = $c->req->param('traits') ? decode_json($c->req->param('traits')) : [];
    if (!_valid_token($token)) {
        $c->stash->{rest} = { error => 'Invalid or expired session; please select the dataset again.' };
        return;
    }
    my $file = _work_dir($c) . "/$token.phenotype.txt";
    if (!-e $file) {
        $c->stash->{rest} = { error => 'The dataset file has expired; please select the dataset again.' };
        return;
    }

    my ($keys, $idx, $rows) = _read_pheno_file($file);
    my @traits = grep { exists($idx->{$_}) } @$traits;
    my @meta = qw | observationUnitName studyName germplasmName replicate blockNumber rowNumber colNumber |;
    my $level_i = $idx->{observationLevel};

    my @out;
    foreach my $r (@$rows) {
        next if defined($level_i) && defined($r->[$level_i]) && $r->[$level_i] ne '' && lc($r->[$level_i]) ne 'plot';
        my @rec = map { defined($idx->{$_}) ? $r->[$idx->{$_}] : undef } @meta;
        my $has_value = 0;
        foreach my $t (@traits) {
            my $v = $r->[$idx->{$t}];
            if (_is_number($v)) { push @rec, $v + 0; $has_value = 1; } else { push @rec, undef; }
        }
        push @out, \@rec if $has_value;
    }

    # every measurement of the traits measured more than once per plot (the
    # dataset file has their plot mean), in date order: the page shows them as
    # the value per plot chosen for the model (mean, sum, first, last...)
    my %repeated;
    my %wanted = map { $_ => 1 } @traits;
    my $rep_file = _work_dir($c) . "/$token.repeated.txt";
    if (-e $rep_file) {
        open(my $fh, '<', $rep_file) or die "Cannot read $rep_file: $!";
        while (my $line = <$fh>) {
            chomp $line;
            my ($unit, $trait, $value) = split /\t/, $line;
            next if !defined($trait) || !$wanted{$trait} || !_is_number($value);
            push @{ $repeated{$trait}->{$unit} }, $value + 0;
        }
        close($fh);
    }

    $c->stash->{rest} = {
        columns => [ qw | unit trial accession rep block row col |, @traits ],
        traits => \@traits,
        rows => \@out,
        repeated => \%repeated,
    };
}

# ---------------------------------------------------------------------------
# Factor support ("smart block") of one trial: which design factors the data
# can support. Same rules as factor_support() in the R pipeline, which applies
# them to the run; here they tell the page which options to allow.
#   rep    a typical test entry (checks excluded) is in >= 2 replicates
#   block  more blocks than replicates, >= 2 plots per block, and some entry
#          in more than one block
#   row,   numbers on >= 90% of the plots, >= 2 levels, >= 2 plots per level,
#   col    not the same grouping as replicate or block
# plots: [{acc, rep, block, row, col, check}]
# ---------------------------------------------------------------------------
sub _n_levels {
    my %u = map { $_ => 1 } grep { defined($_) && $_ ne '' } @_;
    return scalar(keys %u);
}

sub _median {
    my @v = sort { $a <=> $b } @_;
    return 0 if !@v;
    return @v % 2 ? $v[$#v / 2] : ($v[@v / 2 - 1] + $v[@v / 2]) / 2;
}

# the groupings a and b (array refs) are the same partition
sub _same_grouping {
    my ($a, $b) = @_;
    my @k = grep { defined($a->[$_]) && defined($b->[$_]) } 0 .. $#$a;
    return 0 if !@k;
    my $na = _n_levels(map { $a->[$_] } @k);
    return $na == _n_levels(map { $b->[$_] } @k) && $na == _n_levels(map { $a->[$_] . "\t" . $b->[$_] } @k) ? 1 : 0;
}

sub _factor_support {
    my $plots = shift;
    my $yes = { ok => 1, why => '' };
    my $no = sub { return { ok => 0, why => shift } };
    my @p = grep { defined $_->{acc} } @$plots;

    # effective replicate: the block column holds it when there is one replicate
    my @eff = _n_levels(map { $_->{rep} } @p) > 1 ? map { $_->{rep} } @p
            : _n_levels(map { $_->{block} } @p) > 1 ? map { $_->{block} } @p
            : map { '1' } @p;
    my @test = grep { !$p[$_]->{check} } 0 .. $#p;
    @test = 0 .. $#p if !@test;
    my (%reps_of, %copies, %check_copies);
    foreach my $i (@test) { $reps_of{$p[$i]->{acc}}->{$eff[$i] // ''} = 1; $copies{$p[$i]->{acc}}++; }
    $check_copies{$_->{acc}}++ for grep { $_->{check} } @p;
    my $checks_repeated = grep { $_ > 1 } values %check_copies;
    my %sp = (entries_replicated => (_median(values %copies) >= 2 ? 1 : 0));

    $sp{rep} = _n_levels(@eff) < 2 ? $no->('one replicate')
             : _median(map { scalar(keys %$_) } values %reps_of) < 2
                 ? $no->('the test entries are in one replicate only' . ($checks_repeated ? ', only the checks are repeated' : ''))
             : $yes;
    my @rep_used = $sp{rep}->{ok} ? @eff : map { '1' } @p;

    my @bid = map { defined($p[$_]->{block}) && $p[$_]->{block} ne '' ? $rep_used[$_] . "\t" . $p[$_]->{block} : undef } 0 .. $#p;
    my $n_with_block = grep { defined } @bid;
    my %blocks_of;
    $blocks_of{$p[$_]->{acc}}->{$bid[$_]} = 1 for grep { defined $bid[$_] } 0 .. $#p;
    $sp{block} = _n_levels(map { $_->{block} } @p) < 2 ? $no->('one block')
               : _n_levels(@bid) <= _n_levels(@rep_used) ? $no->('the blocks are the replicates')
               : $n_with_block / _n_levels(@bid) < 2 ? $no->('one plot per block')
               : !(grep { keys(%$_) > 1 } values %blocks_of) ? $no->('no entry is in more than one block, so block effects cannot be separated from the genotypes')
               : $yes;
    my @blk_used = $sp{block}->{ok} ? @bid : map { undef } @p;

    my $rc = (grep { defined($_->{row}) && defined($_->{col}) } @p) >= 0.9 * @p;
    foreach my $f (['row', 'row'], ['col', 'column']) {
        my ($k, $nm) = @$f;
        my @x = map { $_->{$k} } @p;
        my $n = _n_levels(@x);
        my @in_rep = map { defined($x[$_]) ? $rep_used[$_] . "\t" . $x[$_] : undef } 0 .. $#p;
        $sp{$k} = (!$rc || $n < 2) ? $no->("no $nm numbers")
                : (grep { defined } @x) / $n < 2 ? $no->("one plot per $nm")
                : ($sp{rep}->{ok} && _same_grouping(\@in_rep, \@rep_used)) ? $no->("each $nm is a replicate")
                : ($sp{block}->{ok} && _same_grouping(\@in_rep, \@blk_used)) ? $no->("each $nm is a block")
                : $yes;
    }
    return \%sp;
}

# ---------------------------------------------------------------------------
# marking outliers in Breedbase
#
#   dataset outliers:  phenotype ids in the dataset's "outliers" list (as the
#                      dataset scatterplot tool stores them); used when a
#                      dataset is read with exclude_dataset_outliers.
#   database outliers: phenotypeprop of type phenotype_outlier (as the
#                      phenotype quality control tool stores them); used by
#                      every search with exclude_phenotype_outlier.
# ---------------------------------------------------------------------------

# Curators and breeders can mark database outliers and remove the mark: in the
# analysis tools breeders have the same power as curators. (The phenotype
# quality control tool lets only curators remove the mark, restoreoutliers.)
sub _can_mark_database {
    my $c = shift;
    return (grep { $_ eq 'curator' || $_ eq 'breeder' } $c->user()->roles()) ? 1 : 0;
}

sub _can_unmark_database {
    my $c = shift;
    return (grep { $_ eq 'curator' || $_ eq 'breeder' } $c->user()->roles()) ? 1 : 0;
}

# items: [{unit, trait}] -> { "unit|trait" => [phenotype_id, ...] } plus database flags
sub _resolve_phenotypes {
    my ($schema, $dataset_trials, $items) = @_;
    my $dbh = $schema->storage->dbh();
    my $outlier_type_id = SGN::Model::Cvterm->get_cvterm_row($schema, 'phenotype_outlier', 'phenotype_property')->cvterm_id();
    my $experiment_type_id = SGN::Model::Cvterm->get_cvterm_row($schema, 'phenotyping_experiment', 'experiment_type')->cvterm_id();

    my (%trait_id, %units);
    foreach my $it (@$items) {
        next if !$it->{unit} || !$it->{trait};
        $units{$it->{unit}} = 1;
        if (!exists $trait_id{$it->{trait}}) {
            my $row = SGN::Model::Cvterm->get_cvterm_row_from_trait_name($schema, $it->{trait});
            $trait_id{$it->{trait}} = $row ? $row->cvterm_id() : undef;
        }
    }
    my %trait_name_of = map { $trait_id{$_} => $_ } grep { defined $trait_id{$_} } keys %trait_id;
    return ({}, {}, $outlier_type_id) if !%units || !%trait_name_of;

    # only phenotypes of plots that belong to the dataset's trials
    my $sth = $dbh->prepare(
        "SELECT stock.uniquename, phenotype.cvalue_id, phenotype.phenotype_id, (pp.phenotype_id IS NOT NULL)
           FROM stock
           JOIN nd_experiment_stock nes ON nes.stock_id = stock.stock_id AND nes.type_id = ?
           JOIN nd_experiment_project nepr ON nepr.nd_experiment_id = nes.nd_experiment_id
           JOIN nd_experiment_phenotype nep ON nep.nd_experiment_id = nes.nd_experiment_id
           JOIN phenotype ON phenotype.phenotype_id = nep.phenotype_id
           LEFT JOIN (SELECT DISTINCT phenotype_id FROM phenotypeprop WHERE type_id = ?) pp ON pp.phenotype_id = phenotype.phenotype_id
          WHERE stock.uniquename = ANY(?) AND phenotype.cvalue_id = ANY(?) AND nepr.project_id = ANY(?)");
    $sth->execute($experiment_type_id, $outlier_type_id, [ keys %units ], [ keys %trait_name_of ], $dataset_trials);

    my %wanted = map { ($_->{unit} . '|' . $_->{trait}) => 1 } @$items;
    my (%ids, %in_db);
    while (my ($unit, $cvterm_id, $phenotype_id, $is_outlier) = $sth->fetchrow_array()) {
        my $key = $unit . '|' . $trait_name_of{$cvterm_id};
        next if !$wanted{$key};
        push @{$ids{$key}}, $phenotype_id;
        $in_db{$phenotype_id} = 1 if $is_outlier;
    }
    return (\%ids, \%in_db, $outlier_type_id);
}

# Compares, for each trial of the dataset, the plot values of its traits in the
# database tables with those in the phenotype search cache
# (materialized_phenotype_jsonb_table), counting distinct phenotype ids on both
# sides. Only the dataset's trials are read, so it stays fast on a large
# database. Returns { stale => [trial names whose counts differ] }.
sub _phenotype_cache_check {
    my ($schema, $ds, $traits) = @_;
    my %trial_name = map { ref($_) ? ($_->[0] => $_->[1]) : ($_ => $_) } @{ $ds->retrieve_trials() || [] };
    my @trial_ids = grep { defined && /^\d+$/ } keys %trial_name;
    return { stale => [] } if !@trial_ids;
    # no traits in the dataset: all traits, as the dataset search does
    my @trait_ids = grep { defined && /^\d+$/ } map { ref($_) ? $_->[0] : $_ } @{ $traits || [] };
    my $dbh = $schema->storage->dbh();
    my $plot_type_id = SGN::Model::Cvterm->get_cvterm_row($schema, 'plot', 'stock_type')->cvterm_id();

    my $trait_sql = @trait_ids ? 'AND phenotype.cvalue_id = ANY(?)' : '';
    my $tables = $dbh->selectall_arrayref(
        "SELECT nepr.project_id, count(DISTINCT phenotype.phenotype_id)
           FROM nd_experiment_project nepr
           JOIN nd_experiment_stock nes ON nes.nd_experiment_id = nepr.nd_experiment_id
           JOIN stock unit ON unit.stock_id = nes.stock_id AND unit.type_id = ?
           JOIN nd_experiment_phenotype nep ON nep.nd_experiment_id = nepr.nd_experiment_id
           JOIN phenotype ON phenotype.phenotype_id = nep.phenotype_id
          WHERE nepr.project_id = ANY(?) AND phenotype.value IS NOT NULL $trait_sql
          GROUP BY nepr.project_id", undef, $plot_type_id, \@trial_ids, (@trait_ids ? \@trait_ids : ()));

    my $trait_json_sql = @trait_ids ? "AND (o->>'trait_id')::int = ANY(?)" : '';
    my $cached = $dbh->selectall_arrayref(
        "SELECT m.trial_id, count(DISTINCT o->>'phenotype_id')
           FROM public.materialized_phenotype_jsonb_table m
           CROSS JOIN LATERAL jsonb_array_elements(m.observations) o
          WHERE m.trial_id = ANY(?) AND m.observationunit_type_name = 'plot' $trait_json_sql
          GROUP BY m.trial_id", undef, \@trial_ids, (@trait_ids ? \@trait_ids : ()));

    my %n_tables = map { $_->[0] => $_->[1] } @$tables;
    my %n_cached = map { $_->[0] => $_->[1] } @$cached;
    my @stale = sort map { $trial_name{$_} } grep { ($n_tables{$_} // 0) != ($n_cached{$_} // 0) } @trial_ids;
    return { stale => \@stale };
}

# Writes the dataset's phenotype file as CXGN::Dataset::File does (tab
# separated, no quotes), but read with the Native search, from the database
# tables instead of the search cache. Same filters as
# CXGN::Dataset::retrieve_phenotypes; outliers are kept (step 2 handles them).
sub _write_native_phenotypes {
    my ($schema, $ds, $traits, $file) = @_;
    my $ids = sub { [ grep { defined } map { ref($_) ? $_->[0] : $_ } @{ $_[0] || [] } ] };
    my $matrix = CXGN::Phenotypes::PhenotypeMatrix->new(
        search_type => 'Native',
        bcs_schema => $schema,
        data_level => $ds->data_level(),
        trait_list => $ids->($traits),
        trial_list => $ids->($ds->retrieve_trials()),
        accession_list => $ids->($ds->retrieve_accessions()),
        exclude_phenotype_outlier => 0,
    );
    my @rows = $matrix->get_phenotype_matrix();
    no warnings 'uninitialized';
    write_file($file, map { my $s = join("\t", @$_); $s =~ s/[\r\n]//g; "$s\n" } @rows);
    return scalar(@rows);
}

# Values of the dataset (plots of its trials, its traits) marked as outliers:
# dataset outliers (the dataset's phenotype id list) and database outliers
# (phenotypeprop phenotype_outlier).
# Returns [{unit, trait, trial, accession, value, dataset, database}].
sub _marked_outliers {
    my ($schema, $ds, $trait_names, $unit_info) = @_;
    my %ds_outliers = map { $_ => 1 } grep { defined && /^\d+$/ } @{ $ds->outliers() || [] };
    my $trials = [ map { ref($_) ? $_->[0] : $_ } @{ $ds->retrieve_trials() || [] } ];
    return [] if !@$trials || !@$trait_names || !%$unit_info;

    my %trait_of;
    foreach my $t (@$trait_names) {
        my $row = SGN::Model::Cvterm->get_cvterm_row_from_trait_name($schema, $t);
        $trait_of{$row->cvterm_id()} = $t if $row;
    }
    return [] if !%trait_of;

    my $outlier_type_id = SGN::Model::Cvterm->get_cvterm_row($schema, 'phenotype_outlier', 'phenotype_property')->cvterm_id();
    my $experiment_type_id = SGN::Model::Cvterm->get_cvterm_row($schema, 'phenotyping_experiment', 'experiment_type')->cvterm_id();
    my $sth = $schema->storage->dbh()->prepare(
        "SELECT stock.uniquename, phenotype.cvalue_id, phenotype.value, phenotype.phenotype_id,
                EXISTS (SELECT 1 FROM phenotypeprop pp WHERE pp.phenotype_id = phenotype.phenotype_id AND pp.type_id = ?)
           FROM phenotype
           JOIN nd_experiment_phenotype nep ON nep.phenotype_id = phenotype.phenotype_id
           JOIN nd_experiment_stock nes ON nes.nd_experiment_id = nep.nd_experiment_id AND nes.type_id = ?
           JOIN nd_experiment_project nepr ON nepr.nd_experiment_id = nep.nd_experiment_id
           JOIN stock ON stock.stock_id = nes.stock_id
          WHERE nepr.project_id = ANY(?) AND phenotype.cvalue_id = ANY(?)
            AND (phenotype.phenotype_id = ANY(?)
                 OR EXISTS (SELECT 1 FROM phenotypeprop pp WHERE pp.phenotype_id = phenotype.phenotype_id AND pp.type_id = ?))");
    $sth->execute($outlier_type_id, $experiment_type_id, $trials, [ keys %trait_of ], [ keys %ds_outliers ], $outlier_type_id);

    my %marked;
    while (my ($unit, $cvterm_id, $value, $phenotype_id, $in_db) = $sth->fetchrow_array()) {
        next if !$unit_info->{$unit};    # plots of the dataset only
        my $key = "$unit|$trait_of{$cvterm_id}";
        my $m = $marked{$key} ||= { unit => $unit, trait => $trait_of{$cvterm_id}, trial => $unit_info->{$unit}->[0],
                                    accession => $unit_info->{$unit}->[1], value => $value, dataset => 0, database => 0 };
        $m->{dataset} = 1 if $ds_outliers{$phenotype_id};
        $m->{database} = 1 if $in_db;
    }
    return [ map { $marked{$_} } sort keys %marked ];
}

# Repeated measurements: traits measured more than once on the same plot
# (trait_repeat_type 'multiple' or 'time_series', or simply several values
# stored for one plot). The dataset file holds one value per plot (Breedbase
# averages them), so every measurement of these traits is written to
# $file (unit, trait, value, date; one line per measurement) for the
# pipeline, which can summarise them differently or model all of them.
# Returns [{trait, short, repeat_type, n_units, n_repeated_units, max_n,
# n_dates, first_date, last_date}], one entry per trait with a repeat type
# other than 'single' or with repeated values in the dataset.
sub _repeated_measurements {
    my ($schema, $ds, $trait_names, $unit_info, $file) = @_;
    my $trials = [ map { ref($_) ? $_->[0] : $_ } @{ $ds->retrieve_trials() || [] } ];
    return [] if !@$trials || !@$trait_names || !%$unit_info;

    my %trait_of;
    foreach my $t (@$trait_names) {
        my $row = SGN::Model::Cvterm->get_cvterm_row_from_trait_name($schema, $t);
        $trait_of{$row->cvterm_id()} = $t if $row;
    }
    return [] if !%trait_of;
    my $dbh = $schema->storage->dbh();

    my %repeat_type;
    my $types = $dbh->selectall_arrayref(
        "SELECT cvtermprop.cvterm_id, cvtermprop.value FROM cvtermprop
           JOIN cvterm proptype ON proptype.cvterm_id = cvtermprop.type_id
          WHERE proptype.name = 'trait_repeat_type' AND cvtermprop.cvterm_id = ANY(?)", undef, [ keys %trait_of ]);
    $repeat_type{ $trait_of{$_->[0]} } = lc($_->[1] // '') for @$types;

    my $experiment_type_id = SGN::Model::Cvterm->get_cvterm_row($schema, 'phenotyping_experiment', 'experiment_type')->cvterm_id();
    my $sth = $dbh->prepare(
        "SELECT stock.uniquename, phenotype.cvalue_id, phenotype.value,
                to_char(phenotype.collect_date, 'YYYY-MM-DD HH24:MI:SS')
           FROM phenotype
           JOIN nd_experiment_phenotype nep ON nep.phenotype_id = phenotype.phenotype_id
           JOIN nd_experiment_stock nes ON nes.nd_experiment_id = nep.nd_experiment_id AND nes.type_id = ?
           JOIN nd_experiment_project nepr ON nepr.nd_experiment_id = nep.nd_experiment_id
           JOIN stock ON stock.stock_id = nes.stock_id
          WHERE nepr.project_id = ANY(?) AND phenotype.cvalue_id = ANY(?)
          ORDER BY phenotype.collect_date NULLS LAST, phenotype.phenotype_id");
    $sth->execute($experiment_type_id, $trials, [ keys %trait_of ]);

    my %values;    # trait -> unit -> [[value, date], ...]
    while (my ($unit, $cvterm_id, $value, $date) = $sth->fetchrow_array()) {
        next if !$unit_info->{$unit} || !_is_number($value);    # plots of the dataset, numeric values
        push @{ $values{ $trait_of{$cvterm_id} }->{$unit} }, [ $value + 0, $date // '' ];
    }

    my (@summary, @lines);
    foreach my $t (sort values %trait_of) {
        my $units = $values{$t} || {};
        my @rep_units = grep { @{ $units->{$_} } > 1 } keys %$units;
        my $type = $repeat_type{$t} // 'single';
        next if !@rep_units && ($type eq 'single' || $type eq '');
        my %dates;
        my $max_n = 0;
        foreach my $u (keys %$units) {
            my $n = scalar @{ $units->{$u} };
            $max_n = $n if $n > $max_n;
            foreach my $m (@{ $units->{$u} }) {
                $dates{ substr($m->[1], 0, 10) } = 1 if $m->[1] ne '';
                push @lines, join("\t", $u, $t, $m->[0], $m->[1]) if @rep_units;
            }
        }
        my @d = sort keys %dates;
        push @summary, {
            trait => $t, short => _short_trait($t), repeat_type => $type,
            n_units => scalar(keys %$units) + 0, n_repeated_units => scalar(@rep_units) + 0, max_n => $max_n + 0,
            n_dates => scalar(@d) + 0, first_date => $d[0], last_date => $d[-1],
        };
    }
    if (@lines) {
        open(my $F, '>', $file) or die "Cannot write the repeated measurements file\n";
        print $F join("\n", "unit\ttrait\tvalue\tdate", @lines), "\n";
        close($F);
    }
    return \@summary;
}

# Genotyping protocols with genotypes of the given accessions (directly or
# through their tissue samples): [{protocol_id, name, n_genotyped, n_markers}],
# most genotyped accessions first.
sub _genotyping_protocols {
    my ($schema, $accession_ids) = @_;
    return [] if !@$accession_ids;
    my $dbh = $schema->storage->dbh();
    my $sql = "WITH acc AS (SELECT unnest(?::int[]) AS id),
          st AS (SELECT id AS stock_id, id AS acc FROM acc
                 UNION SELECT sr.subject_id, sr.object_id FROM stock_relationship sr JOIN acc ON acc.id = sr.object_id
                  WHERE sr.type_id IN (SELECT cvterm_id FROM cvterm WHERE name = 'tissue_sample_of'))
        SELECT nep.nd_protocol_id, p.name, count(DISTINCT st.acc)
          FROM st
          JOIN nd_experiment_stock nes ON nes.stock_id = st.stock_id
          JOIN nd_experiment e ON e.nd_experiment_id = nes.nd_experiment_id
               AND e.type_id IN (SELECT cvterm_id FROM cvterm WHERE name = 'genotyping_experiment')
          JOIN nd_experiment_protocol nep ON nep.nd_experiment_id = e.nd_experiment_id
          JOIN nd_protocol p ON p.nd_protocol_id = nep.nd_protocol_id
         GROUP BY 1, 2";
    my $rows = $dbh->selectall_arrayref($sql, undef, $accession_ids);
    my @out;
    foreach my $r (@$rows) {
        my ($markers) = $dbh->selectrow_array(
            "SELECT sum((c.value->>'marker_count')::int) FROM nd_protocolprop pp
               JOIN cvterm t ON t.cvterm_id = pp.type_id AND t.name = 'vcf_map_details',
                    jsonb_each(pp.value->'chromosomes') c
              WHERE pp.nd_protocol_id = ?", undef, $r->[0]);
        push @out, { protocol_id => $r->[0] + 0, name => $r->[1], n_genotyped => $r->[2] + 0, n_markers => defined($markers) ? $markers + 0 : undef };
    }
    return [ sort { $b->{n_genotyped} <=> $a->{n_genotyped} || $a->{name} cmp $b->{name} } @out ];
}

# The genomic (G) and single-step (H) models need the marker dosages of a
# genotyping protocol: the job retrieves them first (bin/script_factory_genotypes.pl;
# can take minutes the first time, then cached). The database connection goes
# to that step in a file readable by the web server user only, deleted as soon
# as it is read: the password is never on a command line nor in the job record.
# Returns the command of that step, or an error message (string ref).
sub _genotypes_step {
    my ($c, $recipe, $run_base, $dataset_id) = @_;
    my $g = ref($recipe->{genetic}) eq 'HASH' ? $recipe->{genetic} : {};
    my $protocol_id = $g->{protocol_id};
    return \'Choose the genotyping protocol of the genomic model (step 3).' if !defined($protocol_id) || $protocol_id !~ /^\d+$/;
    return \'The genomic model needs a dataset.' if !defined($dataset_id) || $dataset_id !~ /^\d+$/;
    my ($schema, $people_schema) = _schemas($c);
    my $ds = CXGN::Dataset->new(people_schema => $people_schema, schema => $schema, sp_dataset_id => $dataset_id);
    my @ids = map { $_->[0] } @{ $ds->retrieve_accessions() || [] };
    return \'The dataset has no accessions.' if !@ids;
    write_file("$run_base.accessions.txt", join("\n", @ids) . "\n");
    my $conf = { dbhost => $c->config->{dbhost}, dbname => $c->config->{dbname}, dbuser => $c->config->{dbuser}, dbpass => $c->config->{dbpass},
                 cache_root => $c->config->{cache_file_path}, shared_tempdir => $c->config->{cluster_shared_tempdir}, backend => $c->config->{backend},
                 cluster_host => $c->config->{cluster_host}, queue => $c->config->{'web_cluster_queue'}, basepath => $c->config->{basepath} };
    my $old = umask(077);
    write_file("$run_base.dbconf.json", encode_json($conf));
    umask($old);
    chmod(0600, "$run_base.dbconf.json");
    my $basepath = $c->config->{basepath};
    return join(" ", "perl", "-I" . _shell_quote("$basepath/lib"), map { _shell_quote($_) } (
        "$basepath/bin/script_factory_genotypes.pl", "--conf=$run_base.dbconf.json", "--protocol=$protocol_id",
        "--accessions=$run_base.accessions.txt", "--out=$run_base.genotypes.txt"));
}

sub mark_outliers : Path('/ajax/script_factory/outliers/mark') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);

    my $dataset_id = $c->req->param('dataset_id');
    my $action = $c->req->param('action') || 'check';    # check | dataset | database | unmark_dataset | unmark_database
    my $items = try { decode_json($c->req->param('items') || '[]') } catch { undef };
    if (!$dataset_id || $dataset_id !~ /^\d+$/ || ref($items) ne 'ARRAY' || $action !~ /^(check|dataset|database|unmark_dataset|unmark_database)$/) {
        $c->stash->{rest} = { error => 'Invalid request.' };
        return;
    }

    my ($schema, $people_schema, $sp_person_id) = _schemas($c);
    my $ds;
    try {
        $ds = CXGN::Dataset->new({ schema => $schema, people_schema => $people_schema, sp_dataset_id => $dataset_id });
    } catch {
        $c->stash->{rest} = { error => 'Dataset not found.' };
    };
    return if $c->stash->{rest};
    my $is_owner = (($ds->sp_person_id() // -1) == $sp_person_id) ? 1 : 0;
    my $can_db = _can_mark_database($c);
    my $can_unmark_db = _can_unmark_database($c);

    if ($action =~ /dataset$/ && !$is_owner) {
        $c->stash->{rest} = { error => 'Only the owner of the dataset can change its outliers. You can copy the dataset to your own account and mark them there.' };
        return;
    }
    if ($action eq 'database' && !$can_db) {
        $c->stash->{rest} = { error => 'Only curators and breeders can mark outliers in the database.' };
        return;
    }
    if ($action eq 'unmark_database' && !$can_unmark_db) {
        $c->stash->{rest} = { error => 'Only curators and breeders can remove the database outlier mark.' };
        return;
    }

    my $trials = [ map { ref($_) ? $_->[0] : $_ } @{ $ds->retrieve_trials() || [] } ];
    my ($ids, $in_db, $outlier_type_id) = _resolve_phenotypes($schema, $trials, $items);
    my @phenotype_ids = map { @$_ } values %$ids;
    my %ds_outliers = map { $_ => 1 } grep { defined } @{ $ds->outliers() || [] };
    my $dbh = $schema->storage->dbh();
    my $changed = 0;

    if ($action eq 'dataset' || $action eq 'unmark_dataset') {
        foreach my $id (@phenotype_ids) {
            if ($action eq 'dataset') { $changed++ if !$ds_outliers{$id}; $ds_outliers{$id} = 1; }
            else { $changed++ if delete $ds_outliers{$id}; }
        }
        if ($changed) {
            # phenotype ids as strings, the format the dataset tools store
            $ds->outliers([ map { "$_" } sort { $a <=> $b } map { $_ + 0 } keys %ds_outliers ]);
            $ds->store();
        }
    }
    elsif ($action eq 'database' && @phenotype_ids) {
        $changed = $dbh->do(
            "INSERT INTO phenotypeprop (phenotype_id, type_id, value)
             SELECT p.phenotype_id, ?, p.value FROM phenotype p
              WHERE p.phenotype_id = ANY(?)
                AND NOT EXISTS (SELECT 1 FROM phenotypeprop pp WHERE pp.phenotype_id = p.phenotype_id AND pp.type_id = ?)",
            undef, $outlier_type_id, \@phenotype_ids, $outlier_type_id) + 0;
        $in_db->{$_} = 1 for @phenotype_ids;
    }
    elsif ($action eq 'unmark_database' && @phenotype_ids) {
        $changed = $dbh->do("DELETE FROM phenotypeprop WHERE type_id = ? AND phenotype_id = ANY(?)", undef, $outlier_type_id, \@phenotype_ids) + 0;
        delete $in_db->{$_} for @phenotype_ids;
    }

    my %status;
    foreach my $key (keys %$ids) {
        my @p = @{$ids->{$key}};
        $status{$key} = {
            dataset => (grep { $ds_outliers{$_} } @p) ? 1 : 0,
            database => (grep { $in_db->{$_} } @p) ? 1 : 0,
        };
    }
    print STDERR "Analysis Pipeline: $action on dataset $dataset_id by person $sp_person_id, $changed phenotype(s) changed\n" if $action ne 'check';

    $c->stash->{rest} = {
        status => \%status,
        changed => $changed,
        not_found => scalar(grep { !$ids->{$_->{unit} . '|' . $_->{trait}} } @$items),
        dataset_n_outliers => scalar(keys %ds_outliers),
        is_owner => $is_owner,
        can_mark_database => $can_db,
        can_unmark_database => $can_unmark_db,
    };
}

# ---------------------------------------------------------------------------
# running the pipeline
# ---------------------------------------------------------------------------

sub run : Path('/ajax/script_factory/run') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);

    my $token = $c->req->param('token');
    my $recipe_json = $c->req->param('recipe');
    my $exclusions_json = $c->req->param('exclusions') || '[]';
    my $mode = $c->req->param('mode') || 'full';

    if (!_valid_token($token) || !-e _work_dir($c) . "/$token.phenotype.txt") {
        $c->stash->{rest} = { error => 'The dataset file has expired; please select the dataset again.' };
        return;
    }

    my ($recipe, $exclusions);
    try {
        $recipe = decode_json($recipe_json);
        $exclusions = decode_json($exclusions_json);
    } catch {
        $c->stash->{rest} = { error => "Invalid analysis definition: $_" };
    };
    return if $c->stash->{rest};

    if (!$recipe->{traits} || !@{$recipe->{traits}}) {
        $c->stash->{rest} = { error => 'Please select at least one trait.' };
        return;
    }
    $recipe->{stop_after} = 'outliers' if $mode eq 'preview';

    # the R pipeline validates custom formulas token by token; refuse anything
    # outside the formula alphabet before it gets there
    my $single = ref($recipe->{single}) eq 'HASH' ? $recipe->{single} : {};
    if (($single->{mode} // '') eq 'custom' && ($single->{formula} // '') !~ /^[A-Za-z0-9_.\s+\-*\/:|()~]*$/) {
        $c->stash->{rest} = { error => 'The custom model formula contains characters that are not allowed. Use variable names, + - * / : | ( ) 0 and 1 only.' };
        return;
    }

    # environmental zones on a Breedbase accession list: the list is read here
    # (own or public lists only) and its items go to R inside the recipe
    my $zones = ref($recipe->{zones}) eq 'HASH' ? $recipe->{zones} : {};
    my $zacc = ref($zones->{accessions}) eq 'HASH' ? $zones->{accessions} : undef;
    if ($zones->{enabled} && $zacc && ($zacc->{set} // '') eq 'list') {
        my $items = _zone_list_items($c, $zacc->{list_id});
        if (!ref($items)) {
            $c->stash->{rest} = { error => $items };
            return;
        }
        $zacc->{items} = $items;
    }

    my $dir = _work_dir($c);
    my ($fh, $run_base) = tempfile("sf_run_XXXXXXXX", DIR => $dir);
    close($fh);
    my $run_id = basename($run_base);

    write_file("$run_base.exclusions.json", encode_json($exclusions || []));

    my ($schema, $people_schema, $sp_person_id) = _schemas($c);
    my $dataset_id = $c->req->param('dataset_id');
    my %meta = (
        sp_person_id => $sp_person_id,
        mode => $mode,
        created => DateTime->now()->iso8601(),
        script_name => $recipe->{name} // '',
        dataset_id => (defined($dataset_id) && $dataset_id =~ /^\d+$/) ? $dataset_id : undef,
        dataset_name => scalar($c->req->param('dataset_name')) // '',
        token => $token,    # input files of the run (archived when the analysis is stored)
    );
    # email when the run ends (address from the account, never from the request)
    if ($mode ne 'preview' && $c->req->param('notify')) {
        my $person = $c->user()->get_object();
        my $email = $person->get_contact_email() || $person->get_private_email();
        if ($email && $email =~ /^[^\s@]+@[^\s@]+$/) {
            (my $site = $c->req->base . '') =~ s{/+$}{};
            $meta{notify_email} = $email;
            $meta{site_url} = $site;
        }
    }

    my $pedigree_file = "$dir/$token.pedigree.txt";
    my $repeated_file = "$dir/$token.repeated.txt";
    my $f90_dir = blupf90_dir($c);
    my $engine = _run_engine($recipe, $f90_dir);
    $recipe->{engine} = $engine;
    delete $recipe->{engine_reason};
    $meta{engine} = $engine;
    my @args = (
        "$dir/$token.phenotype.txt",
        "$run_base.recipe.json",
        "$run_base.results.json",
        "$run_base.exclusions.json",
        $run_base,
        (-s $pedigree_file ? ("--pedigree=$pedigree_file") : ()),
        (-s $repeated_file ? ("--repeated=$repeated_file") : ()),
    );
    my $basepath = $c->config->{basepath};
    my $gmodel = ref($recipe->{genetic}) eq 'HASH' ? ($recipe->{genetic}->{model} // '') : '';
    my $geno_cmd;
    if ($gmodel eq 'genomic' || $gmodel eq 'single_step') {
        if ($engine ne 'blupf90' && !aghmatrix_available()) {
            $c->stash->{rest} = { error => 'The genomic (G) and single-step (H) models need BLUPF90+ or, with the R engine, the R package AGHmatrix; neither is available on this server.' };
            return;
        }
        my $step = _genotypes_step($c, $recipe, $run_base, $meta{dataset_id});
        if (ref($step)) {
            $c->stash->{rest} = { error => $$step };
            return;
        }
        $geno_cmd = $step;
        push @args, "--genotypes=$run_base.genotypes.txt";
    }
    my $cmd = ($engine eq 'blupf90')
        # BLUPF90+ engine: Perl and blupf90+ only, R is not started
        ? join(" ", "BLUPF90_DIR=" . _shell_quote($f90_dir), "perl", "-I" . _shell_quote("$basepath/lib"), map { _shell_quote($_) } ("$basepath/$F90_PIPELINE", @args))
        : join(" ", "Rscript", map { _shell_quote($_) } ("$basepath/$PIPELINE", @args));
    $cmd .= " > " . _shell_quote("$run_base.log") . " 2>&1";
    # genotypes first (its messages start the log)
    $cmd = "$geno_cmd > " . _shell_quote("$run_base.log") . " 2>&1; " . ($cmd =~ s/ > (\S+) 2>&1$/ >> $1 2>&1/r) if $geno_cmd;
    write_file("$run_base.recipe.json", encode_json($recipe));
    if ($meta{notify_email}) {
        $cmd .= "; perl -I" . _shell_quote("$basepath/lib") . " " . _shell_quote("$basepath/bin/script_factory_notify.pl")
            . " " . _shell_quote($run_base) . " >> " . _shell_quote("$run_base.log") . " 2>&1";
    }

    my $job;
    try {
        $job = CXGN::Job->new({ _job_args($c,
            schema => $schema,
            people_schema => $people_schema,
            sp_person_id => $sp_person_id,
            name => _job_name($recipe, $mode, $meta{dataset_name}, scalar($c->req->param('label'))),
            job_type => 'script_factory_analysis',
            cmd => $cmd,
            results_page => ($mode eq 'preview' ? '/tools/script_factory' : "/tools/script_factory/results/$run_id"),
            cxgn_tools_run_config => {
                backend => $c->config->{backend},
                submit_host => $c->config->{cluster_host},
                temp_base => $dir,
                queue => $c->config->{'web_cluster_queue'},
                do_cleanup => 0,
                max_cluster_jobs => 1_000_000_000,
            },
        ) });
        if (_slurm_ready($c)) {
            $job->submit();
        } else {
            print STDERR "Analysis Pipeline: no Slurm node available, starting run $run_id on the web server\n";
            $job->store();
            _start_local($job, $cmd);
            $meta{started_locally} = 1;
        }
    } catch {
        $c->stash->{rest} = { error => "Could not submit the analysis: $_" };
    };
    return if $c->stash->{rest};

    $meta{job_id} = $job->sp_job_id();
    $meta{cmd} = $cmd;    # to start the run on the web server if the queue cannot
    write_file("$run_base.meta.json", encode_json(\%meta));

    $c->stash->{rest} = { job_id => $job->sp_job_id(), run_id => $run_id };
}

# Read the results of a run, publish its csv files and prepare the genotype
# values in the format expected by /ajax/analysis/store/json.
sub _load_results {
    my ($c, $run_id) = @_;
    my $dir = _work_dir($c);
    my $results_file = "$dir/$run_id.results.json";
    my $results = decode_json(read_file($results_file));
    my $meta = _run_meta($c, $run_id) || {};
    $results->{stored} = $meta->{stored} if $meta->{stored};
    $results->{programs} = _run_programs($c, $meta);
    $results->{dataset_name} //= $meta->{dataset_name};
    $results->{script_name} //= $meta->{script_name};

    # publish downloadable files
    my $public_dir = _public_dir($c);
    my %files;
    foreach my $k (keys %{$results->{files} || {}}) {
        my $f = $results->{files}->{$k};
        next if !$f || ref($f);
        $f = basename($f);
        next if $f !~ /^sf_run_[A-Za-z0-9_]+(\.csv|_blupf90\.tar\.gz)$/;
        copy("$dir/$f", "$public_dir/$f");
        $files{$k} = "/documents/tempfiles/$TMP_SUBDIR/$f";
    }
    $results->{files} = \%files;

    # values ready for /ajax/analysis/store/json
    if ($results->{genotype_values_long}) {
        my $now = DateTime->now();
        my $timestamp = $now->ymd() . "T" . $now->hms();
        my $operator = $c->user()->get_object()->get_first_name() . " " . $c->user()->get_object()->get_last_name();
        my %values;
        my %acc;
        my %traits;
        foreach my $r (@{$results->{genotype_values_long}}) {
            next if !defined($r->{value});
            $values{$r->{accession}}->{$r->{trait_full}} = [ $r->{value}, $timestamp, $operator, "", "" ];
            $acc{$r->{accession}} = 1;
            $traits{$r->{trait_full}} = 1;
        }
        my $terms = _statistical_terms($results);
        my @not_stored = sort grep { defined($terms->{$_}) && $terms->{$_} eq '' } keys %traits;
        foreach my $trait (@not_stored) {
            delete $traits{$trait};
            delete $terms->{$trait};
            delete $_->{$trait} for values %values;
        }
        delete $values{$_} for grep { !%{ $values{$_} } } keys %values;
        %acc = map { $_ => 1 } keys %values;
        $results->{store} = {
            result_values => \%values,
            accession_names => [ sort keys %acc ],
            trait_names => [ sort keys %traits ],
            statistical_terms => $terms,
        };
        delete $results->{genotype_values_long};
        $results->{saved_as} = [
            @{ _saved_as($c, $results->{store}) },
            map { { trait => $_, not_stored => 'Raw values of an unreplicated trial: no model was fitted, and the values are already in the database.' } } @not_stored
        ];
    }

    return $results;
}

# Statistical ontology (SGNSTAT) terms of the stored values. Stored values are
# not measurements of the trait, so each trait is post-composed with the term
# that describes how its values were computed. The term is chosen per trait
# from what the model really did (an engine or pedigree fallback changes it).
my %STAT_TERMS = (
    'R|blup'               => 'Adjusted means from BLUPs using LMER R|SGNSTAT:0000034',
    'R|blue'               => 'Adjusted means from BLUEs using LMER R|SGNSTAT:0000036',
    # runs made before sommer was removed from the pipeline (SF_VERSION <= 1.2)
    'sommer|blup'          => 'Adjusted means from BLUPs using Sommer R|SGNSTAT:0000039',
    'sommer|pedigree'      => 'Adjusted means from BLUPs using Sommer R|SGNSTAT:0000039',
    'BLUPF90+|blup'        => 'Adjusted means from BLUPs using BLUPF90+|SGNSTAT:0000055',
    'BLUPF90+|blue'        => 'Adjusted means from BLUEs using BLUPF90+|SGNSTAT:0000056',
    'BLUPF90+|pedigree'    => 'Adjusted means from pedigree-based BLUPs using BLUPF90+|SGNSTAT:0000057',
    'BLUPF90+|genomic'     => 'GEBVs from genomic BLUPs (G matrix, GBLUP) using BLUPF90+|SGNSTAT:0000058',
    'BLUPF90+|single_step' => 'GEBVs from single-step genomic BLUPs (H matrix, ssGBLUP) using BLUPF90+|SGNSTAT:0000059',
    'SpATS|blue'           => 'Adjusted Means from Spatial Correction using SpATS R|SGNSTAT:0000054',
);

# trait (full name) => SGNSTAT term
sub _statistical_terms {
    my ($results) = @_;
    my $as_list = sub { my $x = shift; return !defined($x) ? [] : ref($x) eq 'ARRAY' ? $x : [ $x ] };
    my $summary = $results->{summary} || {};
    my @short = @{ $as_list->($summary->{traits}) };
    my @full = @{ $as_list->($summary->{traits_full}) };
    my %full_of = map { $short[$_] => $full[$_] } grep { defined $full[$_] } 0 .. $#short;
    my %row_of = map { (($full_of{$_->{trait} // ''} // $_->{trait} // '') => $_) } @{ $as_list->($results->{stage2}) };
    my %stage1_models;
    push @{ $stage1_models{ $full_of{$_->{trait} // ''} // $_->{trait} // '' } }, $_->{model} // '' for @{ $as_list->($results->{stage1}) };

    my $random = ($results->{genotype_effect} // 'random') eq 'random';
    my $run_engine = ($results->{engine} // '') eq 'blupf90' ? 'BLUPF90+' : 'R';
    my %terms;
    foreach my $r (@{ $as_list->($results->{genotype_values_long}) }) {
        my $trait = $r->{trait_full} // next;
        next if $terms{$trait};
        my $row = $row_of{$trait} || {};
        my $model = $row->{model} // '';
        # a trait from a single trial keeps its stage 1 means: BLUEs from SpATS
        # or from the design model, or raw values when the trial is unreplicated
        # (these are already in the database and are not stored again: '')
        if ($model =~ /^Single trial: stage 1 means/) {
            my @m = @{ $stage1_models{$trait} || [] };
            my $all = sub { my $re = shift; return @m && !grep { $_ !~ $re } @m };
            $terms{$trait} = $all->(qr/^Unreplicated/) ? ''
                : $all->(qr/^SpATS/) ? $STAT_TERMS{'SpATS|blue'}
                : $all->(qr/^BLUPF90\+: /) ? $STAT_TERMS{'BLUPF90+|blue'}
                : $STAT_TERMS{'R|blue'};
            next;
        }
        # engine and pedigree use recorded by the pipeline (SF_VERSION >= 1.3); older runs: from the model text
        my $engine = $row->{engine_used} // ($model =~ /^BLUPF90\+: / ? 'BLUPF90+' : $model =~ /^sommer: / ? 'sommer' : $model ne '' ? 'R' : $run_engine);
        my $pedigree = defined($row->{pedigree_used}) ? $row->{pedigree_used} : ($model =~ /A s2a/ && $engine ne 'R');
        my $rel = $row->{relationship} // '';
        my $kind = !$random ? 'blue' : $rel eq 'G' ? 'genomic' : $rel eq 'H' ? 'single_step' : ($pedigree && $pedigree ne 'false') ? 'pedigree' : 'blup';
        $terms{$trait} = $STAT_TERMS{"$engine|$kind"} // $STAT_TERMS{"R|$kind"} // $STAT_TERMS{'R|blup'};
    }
    return \%terms;
}

# What each trait will be stored as: the existing post-composed trait, or the
# name of the one that will be created when the analysis is stored.
sub _saved_as {
    my ($c, $store) = @_;
    my ($schema) = _schemas($c);
    my $delimiter = $c->config->{composable_cvterm_delimiter} || '|';
    my @rows;
    foreach my $trait (@{ $store->{trait_names} || [] }) {
        my $term = $store->{statistical_terms}->{$trait} // '';
        my $trait_row = SGN::Model::Cvterm->get_cvterm_row_from_trait_name($schema, $trait);
        my $stat_row = $term ? SGN::Model::Cvterm->get_cvterm_row_from_trait_name($schema, $term) : undef;
        my ($stat_name) = $term =~ /^(.*)\|[^|]+$/;
        my $row = { trait => $trait, statistical_term => $term, statistical_term_name => $stat_name // $term };
        if (!$trait_row || !$stat_row) {
            $row->{error} = !$trait_row ? 'The trait is not in the database.' : 'The statistical term is not in the database (run the db patch AddScriptFactoryStatisticsTerms).';
        } else {
            my $existing = SGN::Model::Cvterm->get_trait_from_exact_components($schema, [ $trait_row->cvterm_id(), $stat_row->cvterm_id() ]);
            $row->{saved_as} = $existing
                ? SGN::Model::Cvterm::get_trait_from_cvterm_id($schema, $existing, 'extended')
                : $trait_row->name() . $delimiter . $stat_row->name();
            $row->{is_new} = $existing ? 0 : 1;
        }
        push @rows, $row;
    }
    return \@rows;
}

# breeding programs of the run's phenotype file, most plots first
sub _run_programs {
    my ($c, $meta) = @_;
    my $token = $meta->{token};
    return [] if !$token || !_valid_token($token);
    my $file = _work_dir($c) . "/$token.phenotype.txt";
    return [] if !-e $file;
    my %p;
    try {
        my ($keys, $idx, $rows) = _read_pheno_file($file);
        my ($ii, $ni) = ($idx->{programDbId}, $idx->{programName});
        return if !defined $ii;
        foreach my $r (@$rows) {
            my $id = $r->[$ii];
            next if !defined($id) || $id !~ /^\d+$/;
            $p{$id} ||= { id => $id, name => defined($ni) ? $r->[$ni] : $id, n_plots => 0 };
            $p{$id}->{n_plots}++;
        }
    };
    return [ sort { $b->{n_plots} <=> $a->{n_plots} } values %p ];
}

# ---------------------------------------------------------------------------
# Job start. With the Slurm backend a run waits in the queue until a node
# takes it; when no node can (node down, drained or invalid, e.g. after the
# container was recreated) the run would wait forever. Then it is started at
# once on the web server, detached from the request, with the same command and
# the same job record.
# ---------------------------------------------------------------------------
sub _slurm_ready {
    my $c = shift;
    return 1 if lc($c->config->{backend} // '') ne 'slurm';
    my $out = `timeout 5 sinfo -h -o %t 2>/dev/null` // '';
    # usable node states; a trailing * ~ # ! % $ @ marks a node that is not responding or powered down
    return scalar(grep { /^\s*(idle|mix|mixed|alloc|allocated|comp|completing)\s*$/ } split /\n/, $out);
}

sub _start_local {
    my ($job, $cmd) = @_;
    my $finish = try { $job->generate_finish_timestamp_cmd() } catch { '' };
    my $full = "($cmd$finish)";
    system('setsid nohup bash -c ' . _shell_quote($full) . ' > /dev/null 2>&1 < /dev/null &');
    $job->update_status('submitted');
}

