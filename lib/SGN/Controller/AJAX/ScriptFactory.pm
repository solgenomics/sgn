sub export_r : Path('/ajax/script_factory/export_r') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);

    my $recipe_json = $c->req->param('recipe');
    my $name = $c->req->param('name') || 'script_factory_analysis';
    my $recipe;
    try { $recipe = decode_json($recipe_json); } catch { $c->stash->{rest} = { error => 'Invalid script definition.' }; };
    return if $c->stash->{rest};
    delete $recipe->{stop_after};

    my $pretty = JSON->new->canonical(1)->pretty(1)->encode($recipe);
    $pretty =~ s/\)---"/) ---"/g;    # cannot terminate the raw string
    my $pipeline = read_file($c->config->{basepath} . "/$PIPELINE");
    my $user = $c->user()->get_object();
    my $date = DateTime->now()->ymd();
    (my $file_name = $name) =~ s/[^A-Za-z0-9_\-]+/_/g;

    my $script = <<"HEADER";
# =============================================================================
# $name
# Generated by the Breedbase Script Factory on $date
# Author: @{[ $user->get_first_name() ]} @{[ $user->get_last_name() ]}
#
# How to use it on another dataset or another year:
#   1. In Breedbase, download the phenotypes of a dataset or of your trials
#      (tab-delimited "plot" level file, the same file the Script Factory uses).
#   2. Run:  Rscript $file_name.R <phenotype_file.txt> <results.json>
#   3. The results (JSON) and CSV tables are written next to <results.json>.
#
# Required R packages: jsonlite, lme4 (and SpATS for spatial models).
# You can edit the recipe below to change the analysis.
# =============================================================================

RECIPE_JSON <- r"---($pretty)---"

HEADER

    $c->stash->{rest} = { filename => "$file_name.R", script => $script . $pipeline };
}

