
=head1 NAME

SGN::Controller::AJAX::ScriptFactory - AJAX backend for the Script Factory

=head1 DESCRIPTION

Endpoints used by /tools/script_factory:

  /ajax/script_factory/prepare        write the dataset phenotype file, describe traits and trials
  /ajax/script_factory/plot_data      plot level values of selected traits (outlier explorer)
  /ajax/script_factory/run            submit the R pipeline as a background job
  /ajax/script_factory/status         poll a submitted job, return the results when done
  /ajax/script_factory/export_r       standalone R script with the recipe embedded
  /ajax/script_factory/recipes        list saved scripts (own and public)
  /ajax/script_factory/recipe/get     retrieve one saved script
  /ajax/script_factory/recipe/save    create or update a saved script
  /ajax/script_factory/recipe/delete  delete a saved script

Saved scripts live in sgn_people.sp_script_factory_recipe
(db patch AddScriptFactoryRecipeTable).

