sub save_recipe : Path('/ajax/script_factory/recipe/save') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);
    my $dbh = $c->dbc->dbh();
    return _no_table($c) if !_recipe_table_exists($dbh);

    my $sp_person_id = _user_id($c);
    my $id = $c->req->param('recipe_id');
    my $name = $c->req->param('name');
    my $desc = $c->req->param('description') // '';
    my $public = $c->req->param('is_public') ? 1 : 0;
    my $recipe_json = $c->req->param('recipe');

    $name =~ s/^\s+|\s+$//g if defined $name;
    if (!$name) { $c->stash->{rest} = { error => 'Please give the script a name.' }; return; }
    my $recipe;
    try { $recipe = decode_json($recipe_json); } catch { $c->stash->{rest} = { error => 'Invalid script definition.' }; };
    return if $c->stash->{rest};
    delete $recipe->{stop_after};
    $recipe_json = encode_json($recipe);

    if ($id && $id =~ /^\d+$/) {
        my $n = $dbh->do(
            "UPDATE sgn_people.sp_script_factory_recipe SET name = ?, description = ?, is_public = ?, recipe = ?, modified_date = now()
              WHERE sp_script_factory_recipe_id = ? AND sp_person_id = ?", undef,
            $name, $desc, $public, $recipe_json, $id, $sp_person_id);
        if ($n == 0) { $c->stash->{rest} = { error => 'You can only update your own scripts. Use "Save as new" instead.' }; return; }
    } else {
        my ($exists) = $dbh->selectrow_array("SELECT 1 FROM sgn_people.sp_script_factory_recipe WHERE sp_person_id = ? AND name = ?", undef, $sp_person_id, $name);
        if ($exists) { $c->stash->{rest} = { error => "You already have a script named '$name'." }; return; }
        ($id) = $dbh->selectrow_array(
            "INSERT INTO sgn_people.sp_script_factory_recipe (sp_person_id, name, description, is_public, recipe)
             VALUES (?, ?, ?, ?, ?) RETURNING sp_script_factory_recipe_id", undef,
            $sp_person_id, $name, $desc, $public, $recipe_json);
    }
    $c->stash->{rest} = { success => 1, recipe_id => $id };
}

