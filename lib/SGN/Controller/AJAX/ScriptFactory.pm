sub results : Path('/ajax/script_factory/results') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);

    my $run_id = $c->req->param('run_id');
    if (!_valid_token($run_id) || $run_id !~ /^sf_run_/) {
        $c->stash->{rest} = { error => 'Invalid analysis run.' };
        return;
    }
    my $meta = _run_meta($c, $run_id);
    my $dir = _work_dir($c);
    if (!$meta || !-e "$dir/$run_id.results.json") {
        $c->stash->{rest} = { error => (-e "$dir/$run_id.recipe.json" && !-e "$dir/$run_id.results.json" && $meta
            ? 'This analysis has no results yet: it is still running or it failed. Check it on the Analysis Pipeline page.'
            : 'The results of this analysis are no longer available (temporary files are cleaned regularly). Run the script again, or store the analysis to keep its results.') };
        return;
    }
    my $sp_person_id = _user_id($c);
    # stored analyses with a public model can be followed by everyone
    my $public = $meta->{stored} && $meta->{stored}->{is_public};
    if (($meta->{sp_person_id} // -1) != $sp_person_id && !$public && !$c->user()->check_roles('curator')) {
        $c->stash->{rest} = { error => 'This analysis belongs to another user.' };
        return;
    }

    my $results = _load_results($c, $run_id);
    # the dashboard needs only the size of what would be stored
    $results->{store_counts} = {
        n_accessions => scalar(@{ ($results->{store} || {})->{accession_names} || [] }),
        n_traits => scalar(@{ ($results->{store} || {})->{trait_names} || [] }),
    };
    delete $results->{store};

    # coordinates of the trial locations for the maps
    my %names = map { ($_->{location} // '') => 1 } @{ $results->{trials} || [] };
    delete $names{''};
    my %coords;
    if (%names) {
        my ($schema) = _schemas($c);
        my $rs = $schema->resultset("NaturalDiversity::NdGeolocation")->search({ description => { -in => [ keys %names ] } });
        while (my $loc = $rs->next()) {
            my ($lat, $lon) = ($loc->latitude(), $loc->longitude());
            next if !defined($lat) || !defined($lon) || ($lat == 0 && $lon == 0);
            $coords{$loc->description()} = { latitude => $lat + 0, longitude => $lon + 0, altitude => $loc->altitude(), location_id => $loc->nd_geolocation_id() };
        }
    }

    $c->stash->{rest} = {
        run_id => $run_id,
        meta => {
            created => $meta->{created},
            script_name => $meta->{script_name},
            dataset_id => $meta->{dataset_id},
            dataset_name => $meta->{dataset_name},
            job_id => $meta->{job_id},
            is_owner => (($meta->{sp_person_id} // -1) == $sp_person_id) ? 1 : 0,
        },
        locations => \%coords,
        results => $results,
    };
}

sub status : Path('/ajax/script_factory/status') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);

    my $job_id = $c->req->param('job_id');
    my $run_id = $c->req->param('run_id');
    if (!$job_id || $job_id !~ /^\d+$/ || !_valid_token($run_id)) {
        $c->stash->{rest} = { error => 'Invalid job.' };
        return;
    }

    my ($schema, $people_schema, $sp_person_id) = _schemas($c);
    my $job;
    try {
        $job = CXGN::Job->new({ _job_args($c, schema => $schema, people_schema => $people_schema, sp_job_id => $job_id) });
    } catch {
        $c->stash->{rest} = { error => 'This analysis job no longer exists.' };
    };
    return if $c->stash->{rest};

    if (($job->sp_person_id() // -1) != $sp_person_id) {
        $c->stash->{rest} = { error => 'This analysis belongs to another user.' };
        return;
    }

    my $dir = _work_dir($c);
    my $run_base = "$dir/$run_id";
    my $results_file = "$run_base.results.json";
    my $log_file = "$run_base.log";
    # the job backend may be unreachable (or its client library out of date);
    # the run's own files tell us when it is done, so never die here
    my $meta = _run_meta($c, $run_id) || {};
    # still in the queue and no node can take it: start it here, now
    if (!-e $log_file && !$meta->{started_locally} && $meta->{cmd} && ($meta->{job_id} // '') eq $job_id && !_slurm_ready($c)) {
        print STDERR "Analysis Pipeline: job $job_id waits for an unavailable Slurm node, starting run $run_id on the web server\n";
        try { $job->cancel() } catch { print STDERR "Analysis Pipeline: could not cancel the queued job $job_id: $_" };
        $meta->{started_locally} = 1;
        _write_run_meta($c, $run_id, $meta);
        _start_local($job, $meta->{cmd});
    }
    # a run started on the web server has no backend to ask: its files tell when it is done
    my $status = $meta->{started_locally} ? '' : try { $job->check_status() } catch { print STDERR "Analysis Pipeline: cannot check status of job $job_id: $_"; '' };
    $status ||= 'submitted';
    my $progress = '';
    my $halted = 0;
    if (-e $log_file) {
        my @log = read_file($log_file);
        my @lines = grep { /\[script_factory\]/ } @log;
        ($progress = $lines[-1] // '') =~ s/^\[script_factory\]\s*//;
        chomp($progress);
        $halted = grep { /^Execution halted/ } @log;
    }

    my $done = ($halted || $status eq 'finished' || $status eq 'failed' || $status eq 'timed_out' || $status eq 'canceled');
    if (!$done && !-e $results_file) {
        if (!-e $log_file) {
            # the job has not started: it is still waiting for the cluster
            my $waited = time() - ((stat("$run_base.recipe.json"))[9] // time());
            $progress = 'Waiting in the job queue (not started yet)';
            $progress .= sprintf(' for %d min. The job cluster may be busy or down; if this lasts, please contact the site administrator.', $waited / 60) if $waited > 120;
        }
        $c->stash->{rest} = { status => 'running', progress => $progress };
        return;
    }

    if (!-e $results_file) {
        # give a slow shared filesystem a moment
        sleep(2);
    }
    if (!-e $results_file) {
        my $log = -e $log_file ? read_file($log_file) : '';
        my @err = grep { /Error|error|stop|Execution halted/ } split /\n/, $log;
        my $msg = join("\n", @err[ ($#err > 5 ? $#err - 5 : 0) .. $#err ]) || "The analysis job ended with status '$status' without producing results.";
        # say where it stopped (last progress line of the pipeline) before the R details
        $msg = "The analysis stopped at: $progress\n\nDetails:\n$msg" if $progress;
        unlink("$run_base.dbconf.json") if -e "$run_base.dbconf.json";
        $c->stash->{rest} = { status => 'failed', error => $msg };
        return;
    }

    unlink("$run_base.dbconf.json") if -e "$run_base.dbconf.json";
    my $results = _load_results($c, $run_id);
    # the plot level data and the per environment means are only used by the
    # results dashboard; keep the polling response small
    delete $results->{$_} for qw(plots stage1_means recipe);

    $c->stash->{rest} = { status => 'finished', results => $results };
}

