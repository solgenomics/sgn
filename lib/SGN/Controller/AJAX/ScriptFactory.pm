# Engine of a run: 'blupf90' (CXGN::BLUPF90::Pipeline, no R) when the recipe
# asks for BLUPF90+ and blupf90+ is installed; 'lme4' (the R pipeline)
# otherwise.
# Name of a run's job (the jobs list of the user's profile): the saved script's
# name, else the dataset and the traits, so runs are told apart before they
# are stored (storing renames the job to the analysis name, _rename_job).
# label: e.g. 'suggested model' for the model review's second run.
sub _job_name {
    my ($recipe, $mode, $dataset_name, $label) = @_;
    my $base = $mode eq 'preview' ? 'Analysis Pipeline outlier preview' : 'Analysis Pipeline';
    my $what = $recipe->{name};
    if (!defined($what) || $what eq '') {
        my @t = map { my $x = $_; $x =~ s/\|.*$//; $x } @{ ref($recipe->{traits}) eq 'ARRAY' ? $recipe->{traits} : [] };
        my $traits = @t > 3 ? join(', ', @t[0 .. 2]) . ' +' . (@t - 3) : join(', ', @t);
        $what = join(' ', grep { $_ ne '' } ($dataset_name // ''), ($traits ne '' ? "($traits)" : ''));
    }
    $label = '' if !defined($label) || $label !~ /^[\w .()-]{1,40}$/;
    my $name = $base . ($what ne '' ? ": $what" : ' run') . ($label ne '' ? " - $label" : '');
    return length($name) > 200 ? substr($name, 0, 197) . '...' : $name;
}

sub _run_engine {
    my ($recipe, $f90_dir) = @_;
    # the engine chosen in the page: BLUPF90+, or R (lme4, SpATS, glmmTMB,
    # AGHmatrix for relationship matrices). The R engine never hands models to
    # BLUPF90+: when BLUPF90+ cannot be used, R does the whole analysis.
    return ($recipe->{engine} // '') eq 'blupf90' && $f90_dir ? 'blupf90' : 'lme4';
}

sub _write_pedigree {
    my ($schema, $accessions, $file) = @_;
    my $female = SGN::Model::Cvterm->get_cvterm_row($schema, 'female_parent', 'stock_relationship');
    my $male = SGN::Model::Cvterm->get_cvterm_row($schema, 'male_parent', 'stock_relationship');
    return { n_with_parents => 0 } if !$female || !$male || !@$accessions;
    my ($f_id, $m_id) = ($female->cvterm_id(), $male->cvterm_id());
    my $dbh = $schema->storage->dbh();
    my $sth = $dbh->prepare(
        "WITH RECURSIVE ped(stock_id) AS (
             SELECT stock_id FROM stock WHERE uniquename = ANY(?)
           UNION
             SELECT sr.subject_id FROM ped JOIN stock_relationship sr ON sr.object_id = ped.stock_id AND sr.type_id IN (?, ?)
         )
         SELECT s.uniquename,
                (SELECT m.uniquename FROM stock_relationship r JOIN stock m ON m.stock_id = r.subject_id
                  WHERE r.object_id = s.stock_id AND r.type_id = ? ORDER BY r.stock_relationship_id LIMIT 1),
                (SELECT f.uniquename FROM stock_relationship r JOIN stock f ON f.stock_id = r.subject_id
                  WHERE r.object_id = s.stock_id AND r.type_id = ? ORDER BY r.stock_relationship_id LIMIT 1)
           FROM ped JOIN stock s ON s.stock_id = ped.stock_id");
    $sth->execute($accessions, $f_id, $m_id, $f_id, $m_id);
    my %in_data = map { $_ => 1 } @$accessions;
    my (%mothers, %fathers);
    my ($n_parents, $n_both, $n_ancestors) = (0, 0, 0);
    open(my $F, '>', $file) or die "Cannot write the pedigree file\n";
    print $F "Accession\tFemale_Parent\tMale_Parent\n";
    while (my ($acc, $mother, $father) = $sth->fetchrow_array()) {
        print $F join("\t", $acc, $mother // '', $father // '') . "\n";
        if ($in_data{$acc}) {
            $n_parents++ if $mother || $father;
            $n_both++ if $mother && $father;
            $mothers{$mother} = 1 if $mother;
            $fathers{$father} = 1 if $father;
        } else {
            $n_ancestors++;
        }
    }
    close($F);
    return {
        n_with_parents => $n_parents,
        n_with_both => $n_both,
        n_mothers => scalar(keys %mothers),
        n_fathers => scalar(keys %fathers),
        n_ancestors => $n_ancestors,
    };
}

# management factor types (sgn.conf management_factor_types), used to merge
# management factor projects of one type into one factor
sub _treatment_types {
    my $c = shift;
    my $types = $c->config->{management_factor_types} // '';
    my @t = grep { length } map { s/^\s+|\s+$//gr } split /,/, $types;
    return @t ? \@t : [ 'Fertilizer', 'Fungicide', 'Irrigation', 'Drought', 'Herbicide', 'Weeding', 'Pruning', 'Hormone treatment', 'Light treatment' ];
}

# Treatment factors of the dataset, derived like the R pipeline does:
# management factor columns of one type become one factor (levels = rest of
# the project names), treatment variables are a factor each; 'none' where a
# plot has no value.
sub _treatment_factors {
    my ($c, $keys, $idx, $plot_rows, $legacy_cols, $treatment_cols) = @_;
    my $types = _treatment_types($c);
    my %legacy = map { $_ => 1 } @$legacy_cols;
    my $applied = sub { my $v = shift; return defined($v) && $v !~ /^\s*(0|NA)?\s*$/ };
    my $var_name = sub { (my $v = shift) =~ s/[^A-Za-z0-9]+/_/g; $v =~ s/^_+|_+$//g; return "trt_$v" };
    my (%factors, @order);
    foreach my $col (@$treatment_cols) {
        my ($name, $level, $source);
        if ($legacy{$col}) {
            $source = 'management factor';
            ($name, $level) = ($col, 'applied');
            foreach my $type (@$types) {
                (my $re = quotemeta($type)) =~ s/(\\ |_)+/[_ ]/g;
                if ($col =~ /(?:^|[_ ])($re)(?:[_ ]|$)(.*)$/i) {
                    $name = $type;
                    ($level = $2) =~ s/[_ ]+/ /g;
                    $level =~ s/^\s+|\s+$//g;
                    $level = $col if $level eq '';
                    last;
                }
            }
        } else {
            $source = 'treatment variable';
            ($name = $col) =~ s/\|.*$//;
        }
        my $var = $var_name->($name);
        my $f = $factors{$var} ||= do { push @order, $var; { name => $name, variable => $var, source => $source, values => [] } };
        my $i = $idx->{$col};
        for my $r (0 .. $#$plot_rows) {
            my $v = $plot_rows->[$r]->[$i];
            next if !$applied->($v);
            my $l = $legacy{$col} ? $level : ($v =~ s/^\s+|\s+$//gr);
            my $cur = $f->{values}->[$r];
            $f->{values}->[$r] = (!defined($cur) || $cur eq $l) ? $l : "$cur + $l";
        }
    }
    my $trial_i = $idx->{studyName};
    my @out;
    foreach my $var (@order) {
        my $f = $factors{$var};
        my (%n, %by_trial);
        for my $r (0 .. $#$plot_rows) {
            my $l = $f->{values}->[$r] // 'none';
            $n{$l}++;
            $by_trial{ defined($trial_i) ? ($plot_rows->[$r]->[$trial_i] // '') : '' }->{$l}++;
        }
        next if !grep { $_ ne 'none' } keys %n;
        my $within = grep { keys(%$_) > 1 } values %by_trial;
        my %trial_level = map { my @l = sort keys %{$by_trial{$_}}; ($_ => (@l == 1 ? $l[0] : '(mixed)')) } keys %by_trial;
        my %between = map { $_ => 1 } values %trial_level;
        push @out, {
            name => $f->{name},
            variable => $var,
            source => $f->{source},
            levels => [ map { { level => $_, n_plots => $n{$_} } } sort keys %n ],
            varies_within_trials => $within ? 1 : 0,
            n_trials_with_levels => scalar(grep { $_ ne 'none' } values %trial_level),
            n_trial_levels => scalar(keys %between),
            by_trial => [ map { { trial => $_, levels => join(', ', sort keys %{$by_trial{$_}}) } } sort keys %by_trial ],
        };
    }
    return \@out;
}

sub _is_number {
    my $v = shift;
    return defined($v) && $v =~ /^\s*-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?\s*$/ ? 1 : 0;
}

