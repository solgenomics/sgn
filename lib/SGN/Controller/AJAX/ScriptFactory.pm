sub _user_id {
    my $c = shift;
    return $c->user() ? $c->user()->get_object()->get_sp_person_id() : undef;
}

sub _require_login {
    my $c = shift;
    if (!$c->user()) {
        $c->stash->{rest} = { error => 'You must be logged in to use the Script Factory.' };
        return 0;
    }
    return 1;
}

sub _work_dir {
    my $c = shift;
    my $dir = $c->config->{cluster_shared_tempdir} . "/" . $TMP_SUBDIR;
    mkdir $dir if !-d $dir;
    return $dir;
}

sub _public_dir {
    my $c = shift;
    $c->tempfiles_subdir($TMP_SUBDIR);
    my $dir = $c->config->{basepath} . "/static/documents/tempfiles/" . $TMP_SUBDIR;
    mkdir $dir if !-d $dir;
    return $dir;
}

# tokens are basenames generated by File::Temp; never trust anything else
sub _valid_token {
    my $token = shift;
    return defined($token) && $token =~ /^sf_[A-Za-z0-9_]+$/ ? 1 : 0;
}

sub _shell_quote {
    my $value = shift;
    my @parts = split(/'/, $value, -1);
    return "'" . join("'\"'\"'", @parts) . "'";
}

sub _schemas {
    my $c = shift;
    my $sp_person_id = _user_id($c);
    my $people_schema = $c->dbic_schema("CXGN::People::Schema", undef, $sp_person_id);
    my $schema = $c->dbic_schema("Bio::Chado::Schema", "sgn_chado", $sp_person_id);
    return ($schema, $people_schema, $sp_person_id);
}

sub _read_pheno_file {
    my $file = shift;
    open(my $F, "<", $file) or die "Cannot open phenotype file\n";
    my $header = <$F>;
    $header =~ s/\r?\n$//;
    my @keys = split /\t/, $header, -1;
    my @rows;
    while (my $line = <$F>) {
        $line =~ s/\r?\n$//;
        next if $line eq '';
        my @f = split /\t/, $line, -1;
        push @rows, \@f;
    }
    close($F);
    my %idx;
    for (my $i = 0; $i < @keys; $i++) { $idx{$keys[$i]} = $i; }
    return (\@keys, \%idx, \@rows);
}

sub _short_trait {
    my $t = shift;
    $t =~ s/\|.*$//;
    return $t;
}

sub _is_number {
    my $v = shift;
    return defined($v) && $v =~ /^\s*-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?\s*$/ ? 1 : 0;
}

