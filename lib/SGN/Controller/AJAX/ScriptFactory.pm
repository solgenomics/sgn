sub run : Path('/ajax/script_factory/run') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);

    my $token = $c->req->param('token');
    my $recipe_json = $c->req->param('recipe');
    my $exclusions_json = $c->req->param('exclusions') || '[]';
    my $mode = $c->req->param('mode') || 'full';

    if (!_valid_token($token) || !-e _work_dir($c) . "/$token.phenotype.txt") {
        $c->stash->{rest} = { error => 'The dataset file has expired; please select the dataset again.' };
        return;
    }

    my ($recipe, $exclusions);
    try {
        $recipe = decode_json($recipe_json);
        $exclusions = decode_json($exclusions_json);
    } catch {
        $c->stash->{rest} = { error => "Invalid analysis definition: $_" };
    };
    return if $c->stash->{rest};

    if (!$recipe->{traits} || !@{$recipe->{traits}}) {
        $c->stash->{rest} = { error => 'Please select at least one trait.' };
        return;
    }
    $recipe->{stop_after} = 'outliers' if $mode eq 'preview';

    my $dir = _work_dir($c);
    my ($fh, $run_base) = tempfile("sf_run_XXXXXXXX", DIR => $dir);
    close($fh);
    my $run_id = basename($run_base);

    write_file("$run_base.recipe.json", encode_json($recipe));
    write_file("$run_base.exclusions.json", encode_json($exclusions || []));

    my ($schema, $people_schema, $sp_person_id) = _schemas($c);

    my $cmd = join(" ",
        "Rscript",
        map { _shell_quote($_) } (
            $c->config->{basepath} . "/$PIPELINE",
            "$dir/$token.phenotype.txt",
            "$run_base.recipe.json",
            "$run_base.results.json",
            "$run_base.exclusions.json",
            $run_base,
        )
    ) . " > " . _shell_quote("$run_base.log") . " 2>&1";

    my $job;
    try {
        $job = CXGN::Job->new({
            schema => $schema,
            people_schema => $people_schema,
            dbhost => $c->config->{dbhost},
            dbname => $c->config->{dbname},
            dbuser => $c->config->{dbuser},
            dbpass => $c->config->{dbpass},
            basepath => $c->config->{basepath},
            sp_person_id => $sp_person_id,
            name => ($mode eq 'preview' ? 'Script Factory outlier preview' : 'Script Factory analysis') . ($recipe->{name} ? ": $recipe->{name}" : ''),
            job_type => 'script_factory_analysis',
            cmd => $cmd,
            results_page => '/tools/script_factory',
            cxgn_tools_run_config => {
                backend => $c->config->{backend},
                submit_host => $c->config->{cluster_host},
                temp_base => $dir,
                queue => $c->config->{'web_cluster_queue'},
                do_cleanup => 0,
                max_cluster_jobs => 1_000_000_000,
            },
        });
        $job->submit();
    } catch {
        $c->stash->{rest} = { error => "Could not submit the analysis: $_" };
    };
    return if $c->stash->{rest};

    $c->stash->{rest} = { job_id => $job->sp_job_id(), run_id => $run_id };
}

sub status : Path('/ajax/script_factory/status') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);

    my $job_id = $c->req->param('job_id');
    my $run_id = $c->req->param('run_id');
    if (!$job_id || $job_id !~ /^\d+$/ || !_valid_token($run_id)) {
        $c->stash->{rest} = { error => 'Invalid job.' };
        return;
    }

    my ($schema, $people_schema, $sp_person_id) = _schemas($c);
    my $job;
    try {
        $job = CXGN::Job->new({ schema => $schema, people_schema => $people_schema, sp_job_id => $job_id });
    } catch {
        $c->stash->{rest} = { error => 'This analysis job no longer exists.' };
    };
    return if $c->stash->{rest};

    if (($job->sp_person_id() // -1) != $sp_person_id) {
        $c->stash->{rest} = { error => 'This analysis belongs to another user.' };
        return;
    }

    my $dir = _work_dir($c);
    my $run_base = "$dir/$run_id";
    my $results_file = "$run_base.results.json";
    my $log_file = "$run_base.log";
    # the job backend may be unreachable (or its client library out of date);
    # the run's own files tell us when it is done, so never die here
    my $status = try { $job->check_status() } catch { print STDERR "Script Factory: cannot check status of job $job_id: $_"; '' };
    $status ||= 'submitted';
    my $progress = '';
    my $halted = 0;
    if (-e $log_file) {
        my @log = read_file($log_file);
        my @lines = grep { /\[script_factory\]/ } @log;
        ($progress = $lines[-1] // '') =~ s/^\[script_factory\]\s*//;
        chomp($progress);
        $halted = grep { /^Execution halted/ } @log;
    }

    my $done = ($halted || $status eq 'finished' || $status eq 'failed' || $status eq 'timed_out' || $status eq 'canceled');
    if (!$done && !-e $results_file) {
        $c->stash->{rest} = { status => 'running', progress => $progress };
        return;
    }

    if (!-e $results_file) {
        # give a slow shared filesystem a moment
        sleep(2);
    }
    if (!-e $results_file) {
        my $log = -e $log_file ? read_file($log_file) : '';
        my @err = grep { /Error|error|stop|Execution halted/ } split /\n/, $log;
        my $msg = join("\n", @err[ ($#err > 5 ? $#err - 5 : 0) .. $#err ]) || "The analysis job ended with status '$status' without producing results.";
        $c->stash->{rest} = { status => 'failed', error => $msg };
        return;
    }

    my $results = decode_json(read_file($results_file));

    # publish downloadable files
    my $public_dir = _public_dir($c);
    my %files;
    foreach my $k (keys %{$results->{files} || {}}) {
        my $f = $results->{files}->{$k};
        next if !$f || ref($f);
        $f = basename($f);
        next if $f !~ /^sf_run_[A-Za-z0-9_]+\.csv$/;
        copy("$dir/$f", "$public_dir/$f");
        $files{$k} = "/documents/tempfiles/$TMP_SUBDIR/$f";
    }
    $results->{files} = \%files;

    # values ready for /ajax/analysis/store/json
    if ($results->{genotype_values_long}) {
        my $now = DateTime->now();
        my $timestamp = $now->ymd() . "T" . $now->hms();
        my $operator = $c->user()->get_object()->get_first_name() . " " . $c->user()->get_object()->get_last_name();
        my %values;
        my %acc;
        my %traits;
        foreach my $r (@{$results->{genotype_values_long}}) {
            next if !defined($r->{value});
            $values{$r->{accession}}->{$r->{trait_full}} = [ $r->{value}, $timestamp, $operator, "", "" ];
            $acc{$r->{accession}} = 1;
            $traits{$r->{trait_full}} = 1;
        }
        $results->{store} = {
            result_values => \%values,
            accession_names => [ sort keys %acc ],
            trait_names => [ sort keys %traits ],
        };
        delete $results->{genotype_values_long};
    }

    $c->stash->{rest} = { status => 'finished', results => $results };
}

