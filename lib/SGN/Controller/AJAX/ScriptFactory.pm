sub _recipe_table_exists {
    my $dbh = shift;
    my ($exists) = $dbh->selectrow_array("SELECT to_regclass('sgn_people.sp_script_factory_recipe') IS NOT NULL");
    return $exists;
}

sub _no_table {
    my $c = shift;
    $c->stash->{rest} = { error => 'Saving scripts requires the database patch AddScriptFactoryRecipeTable. Please ask your administrator to run it. You can still export the script as an R file or JSON.' };
}

sub list_recipes : Path('/ajax/script_factory/recipes') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);
    my $dbh = $c->dbc->dbh();
    return _no_table($c) if !_recipe_table_exists($dbh);

    my $sp_person_id = _user_id($c);
    my $sth = $dbh->prepare(
        "SELECT r.sp_script_factory_recipe_id, r.name, r.description, r.is_public, r.sp_person_id,
                p.first_name || ' ' || p.last_name, to_char(r.modified_date, 'YYYY-MM-DD HH24:MI'), r.recipe
           FROM sgn_people.sp_script_factory_recipe r
           JOIN sgn_people.sp_person p USING(sp_person_id)
          WHERE r.sp_person_id = ? OR r.is_public
          ORDER BY (r.sp_person_id = ?) DESC, r.modified_date DESC");
    $sth->execute($sp_person_id, $sp_person_id);
    my @recipes;
    while (my ($id, $name, $desc, $public, $owner_id, $owner, $modified, $recipe) = $sth->fetchrow_array()) {
        my $r = try { decode_json($recipe) } catch { {} };
        push @recipes, {
            recipe_id => $id, name => $name, description => $desc, is_public => $public ? 1 : 0,
            is_owner => ($owner_id == $sp_person_id) ? 1 : 0, owner => $owner, modified => $modified,
            strategy => $r->{strategy}, n_traits => scalar(@{$r->{traits} || []}),
            index => $r->{index} && $r->{index}->{enabled} ? 1 : 0,
            zones => $r->{zones} && $r->{zones}->{enabled} ? 1 : 0,
        };
    }
    $c->stash->{rest} = { recipes => \@recipes };
}

sub get_recipe : Path('/ajax/script_factory/recipe/get') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);
    my $dbh = $c->dbc->dbh();
    return _no_table($c) if !_recipe_table_exists($dbh);

    my $id = $c->req->param('recipe_id');
    if (!$id || $id !~ /^\d+$/) { $c->stash->{rest} = { error => 'Invalid script id.' }; return; }
    my ($name, $desc, $public, $owner_id, $recipe) = $dbh->selectrow_array(
        "SELECT name, description, is_public, sp_person_id, recipe FROM sgn_people.sp_script_factory_recipe
          WHERE sp_script_factory_recipe_id = ? AND (sp_person_id = ? OR is_public)", undef, $id, _user_id($c));
    if (!$name) { $c->stash->{rest} = { error => 'Script not found.' }; return; }
    $c->stash->{rest} = {
        recipe_id => $id, name => $name, description => $desc, is_public => $public ? 1 : 0,
        is_owner => ($owner_id == _user_id($c)) ? 1 : 0, recipe => decode_json($recipe),
    };
}

sub save_recipe : Path('/ajax/script_factory/recipe/save') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);
    my $dbh = $c->dbc->dbh();
    return _no_table($c) if !_recipe_table_exists($dbh);

    my $sp_person_id = _user_id($c);
    my $id = $c->req->param('recipe_id');
    my $name = $c->req->param('name');
    my $desc = $c->req->param('description') // '';
    my $public = $c->req->param('is_public') ? 1 : 0;
    my $recipe_json = $c->req->param('recipe');

    $name =~ s/^\s+|\s+$//g if defined $name;
    if (!$name) { $c->stash->{rest} = { error => 'Please give the script a name.' }; return; }
    my $recipe;
    try { $recipe = decode_json($recipe_json); } catch { $c->stash->{rest} = { error => 'Invalid script definition.' }; };
    return if $c->stash->{rest};
    delete $recipe->{stop_after};
    $recipe_json = encode_json($recipe);

    if ($id && $id =~ /^\d+$/) {
        my $n = $dbh->do(
            "UPDATE sgn_people.sp_script_factory_recipe SET name = ?, description = ?, is_public = ?, recipe = ?, modified_date = now()
              WHERE sp_script_factory_recipe_id = ? AND sp_person_id = ?", undef,
            $name, $desc, $public, $recipe_json, $id, $sp_person_id);
        if ($n == 0) { $c->stash->{rest} = { error => 'You can only update your own scripts. Use "Save as new" instead.' }; return; }
    } else {
        my ($exists) = $dbh->selectrow_array("SELECT 1 FROM sgn_people.sp_script_factory_recipe WHERE sp_person_id = ? AND name = ?", undef, $sp_person_id, $name);
        if ($exists) { $c->stash->{rest} = { error => "You already have a script named '$name'." }; return; }
        ($id) = $dbh->selectrow_array(
            "INSERT INTO sgn_people.sp_script_factory_recipe (sp_person_id, name, description, is_public, recipe)
             VALUES (?, ?, ?, ?, ?) RETURNING sp_script_factory_recipe_id", undef,
            $sp_person_id, $name, $desc, $public, $recipe_json);
    }
    $c->stash->{rest} = { success => 1, recipe_id => $id };
}

sub delete_recipe : Path('/ajax/script_factory/recipe/delete') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);
    my $dbh = $c->dbc->dbh();
    return _no_table($c) if !_recipe_table_exists($dbh);

    my $id = $c->req->param('recipe_id');
    my $n = ($id && $id =~ /^\d+$/) ? $dbh->do("DELETE FROM sgn_people.sp_script_factory_recipe WHERE sp_script_factory_recipe_id = ? AND sp_person_id = ?", undef, $id, _user_id($c)) : 0;
    $c->stash->{rest} = $n > 0 ? { success => 1 } : { error => 'Script not found or not yours.' };
}

