sub prepare : Path('/ajax/script_factory/prepare') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);

    my $dataset_id = $c->req->param('dataset_id');
    my $exclude_outliers = $c->req->param('dataset_trait_outliers') ? 1 : 0;
    if (!$dataset_id || $dataset_id !~ /^\d+$/) {
        $c->stash->{rest} = { error => 'Please select a dataset.' };
        return;
    }

    my ($schema, $people_schema) = _schemas($c);
    my $dir = _work_dir($c);
    my ($fh, $tempfile) = tempfile("sf_XXXXXXXX", DIR => $dir);
    close($fh);
    my $token = basename($tempfile);
    my $pheno_file = "$tempfile.phenotype.txt";

    my ($ds, $traits_in_ds);
    try {
        $ds = CXGN::Dataset::File->new(
            people_schema => $people_schema,
            schema => $schema,
            sp_dataset_id => $dataset_id,
            exclude_dataset_outliers => $exclude_outliers,
            exclude_phenotype_outlier => $exclude_outliers,
            file_name => $tempfile,
            quotes => 0,
        );
        $ds->retrieve_phenotypes($pheno_file);
        $traits_in_ds = $ds->retrieve_traits();
    } catch {
        $c->stash->{rest} = { error => "Could not retrieve the dataset phenotypes: $_" };
    };
    return if $c->stash->{rest};

    if (!-s $pheno_file) {
        $c->stash->{rest} = { error => 'The dataset has no phenotypes. Please choose a dataset with trials and traits.' };
        return;
    }

    my ($keys, $idx, $rows) = _read_pheno_file($pheno_file);

    my %trait_names = map { $_->[1] => 1 } @{$traits_in_ds || []};
    my @trait_cols = grep { exists($trait_names{$_}) } @$keys;
    if (!@trait_cols) {
        # fall back to the columns after the seedlot block of the file
        my $start = $idx->{availableGermplasmSeedlotUniquenames};
        @trait_cols = grep { $_ ne 'notes' } @$keys[ ($start // $#$keys) + 1 .. $#$keys ] if defined $start;
    }

    my $level_i = $idx->{observationLevel};
    my @plot_rows = grep { !defined($level_i) || !defined($_->[$level_i]) || $_->[$level_i] eq '' || lc($_->[$level_i]) eq 'plot' } @$rows;

    my @traits;
    foreach my $t (@trait_cols) {
        my $i = $idx->{$t};
        my ($n, $sum, $min, $max) = (0, 0, undef, undef);
        foreach my $r (@plot_rows) {
            my $v = $r->[$i];
            next if !_is_number($v);
            $n++; $sum += $v;
            $min = $v if !defined($min) || $v < $min;
            $max = $v if !defined($max) || $v > $max;
        }
        next if $n == 0;
        push @traits, { name => $t, short => _short_trait($t), n => $n, mean => $sum / $n, min => $min, max => $max };
    }

    my %trials;
    my %accessions;
    my $col = sub { my ($r, $name) = @_; my $i = $idx->{$name}; return defined($i) ? $r->[$i] : undef; };
    foreach my $r (@plot_rows) {
        my $trial = $col->($r, 'studyName') // 'unknown';
        my $t = $trials{$trial} ||= {
            trial => $trial,
            trial_id => $col->($r, 'studyDbId'),
            location => $col->($r, 'locationName'),
            year => $col->($r, 'studyYear'),
            design => $col->($r, 'studyDesign'),
            n_plots => 0, acc => {}, rep => {}, block => {}, row => {}, col => {}, rc => 0,
        };
        $t->{n_plots}++;
        my $acc = $col->($r, 'germplasmName');
        $t->{acc}->{$acc}++ if defined $acc;
        $accessions{$acc} = 1 if defined $acc;
        foreach my $f (['rep', 'replicate'], ['block', 'blockNumber'], ['row', 'rowNumber'], ['col', 'colNumber']) {
            my $v = $col->($r, $f->[1]);
            $t->{$f->[0]}->{$v} = 1 if defined($v) && $v ne '';
        }
        my ($rv, $cv) = ($col->($r, 'rowNumber'), $col->($r, 'colNumber'));
        $t->{rc}++ if _is_number($rv) && _is_number($cv);
    }

    my @trials;
    foreach my $name (sort keys %trials) {
        my $t = $trials{$name};
        my $n_acc = scalar(keys %{$t->{acc}});
        my $replicated = grep { $_ > 1 } values %{$t->{acc}};
        my $has_rowcol = ($t->{rc} >= 0.9 * $t->{n_plots} && keys(%{$t->{row}}) > 1 && keys(%{$t->{col}}) > 1) ? 1 : 0;
        push @trials, {
            trial => $name,
            trial_id => $t->{trial_id},
            location => $t->{location},
            year => $t->{year},
            design => $t->{design},
            n_plots => $t->{n_plots},
            n_accessions => $n_acc,
            n_reps => scalar(keys %{$t->{rep}}),
            n_blocks => scalar(keys %{$t->{block}}),
            n_rows => scalar(keys %{$t->{row}}),
            n_cols => scalar(keys %{$t->{col}}),
            has_rowcol => $has_rowcol,
            replicated => $replicated ? 1 : 0,
        };
    }

    my %locations = map { ($_->{location} // '') => 1 } @trials;
    my %years = map { ($_->{year} // '') => 1 } @trials;

    $c->stash->{rest} = {
        token => $token,
        dataset_id => $dataset_id,
        dataset_name => $ds->name(),
        phenotype_file => $pheno_file,    # archived as training data when the analysis is stored
        traits => \@traits,
        trials => \@trials,
        n_plots => scalar(@plot_rows),
        n_accessions => scalar(keys %accessions),
        n_locations => scalar(keys %locations),
        n_years => scalar(keys %years),
    };
}

sub plot_data : Path('/ajax/script_factory/plot_data') Args(0) {
    my $self = shift;
    my $c = shift;
    return if !_require_login($c);

    my $token = $c->req->param('token');
    my $traits = $c->req->param('traits') ? decode_json($c->req->param('traits')) : [];
    if (!_valid_token($token)) {
        $c->stash->{rest} = { error => 'Invalid or expired session; please select the dataset again.' };
        return;
    }
    my $file = _work_dir($c) . "/$token.phenotype.txt";
    if (!-e $file) {
        $c->stash->{rest} = { error => 'The dataset file has expired; please select the dataset again.' };
        return;
    }

    my ($keys, $idx, $rows) = _read_pheno_file($file);
    my @traits = grep { exists($idx->{$_}) } @$traits;
    my @meta = qw | observationUnitName studyName germplasmName replicate blockNumber rowNumber colNumber |;
    my $level_i = $idx->{observationLevel};

    my @out;
    foreach my $r (@$rows) {
        next if defined($level_i) && defined($r->[$level_i]) && $r->[$level_i] ne '' && lc($r->[$level_i]) ne 'plot';
        my @rec = map { defined($idx->{$_}) ? $r->[$idx->{$_}] : undef } @meta;
        my $has_value = 0;
        foreach my $t (@traits) {
            my $v = $r->[$idx->{$t}];
            if (_is_number($v)) { push @rec, $v + 0; $has_value = 1; } else { push @rec, undef; }
        }
        push @out, \@rec if $has_value;
    }

    $c->stash->{rest} = {
        columns => [ qw | unit trial accession rep block row col |, @traits ],
        traits => \@traits,
        rows => \@out,
    };
}

