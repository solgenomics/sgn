# items of the accession list that defines the environmental zones; the list
# must belong to the user or be public. Returns an array ref, or an error text.
sub _zone_list_items {
    my ($c, $list_id) = @_;
    return 'Choose the accession list used to group environments (step 5).' if !defined($list_id) || $list_id !~ /^\d+$/;
    my $dbh = $c->dbc->dbh();
    my ($owner, $is_public) = $dbh->selectrow_array('SELECT owner, is_public FROM sgn_people.list WHERE list_id = ?', undef, $list_id);
    return 'The accession list chosen to group environments no longer exists; choose another one (step 5).' if !defined($owner) && !defined($is_public);
    return 'You do not have access to the accession list chosen to group environments.' if !$is_public && ($owner // -1) != (_user_id($c) // -2);
    my $items = $dbh->selectcol_arrayref('SELECT content FROM sgn_people.list_item WHERE list_id = ? ORDER BY list_item_id', undef, $list_id);
    my %seen;
    my @items = grep { defined($_) && $_ ne '' && !$seen{$_}++ } map { my $x = $_; $x =~ s/^\s+|\s+$//g; $x } @{$items || []};
    return 'The accession list chosen to group environments is empty.' if !@items;
    return \@items;
}

sub _read_pheno_file {
    my $file = shift;
    open(my $F, "<", $file) or die "Cannot open phenotype file\n";
    my $header = <$F>;
    $header =~ s/\r?\n$//;
    my @keys = split /\t/, $header, -1;
    my @rows;
    while (my $line = <$F>) {
        $line =~ s/\r?\n$//;
        next if $line eq '';
        my @f = split /\t/, $line, -1;
        push @rows, \@f;
    }
    close($F);
    my %idx;
    for (my $i = 0; $i < @keys; $i++) { $idx{$keys[$i]} = $i; }
    return (\@keys, \%idx, \@rows);
}

sub _short_trait {
    my $t = shift;
    $t =~ s/\|.*$//;
    return $t;
}

# Directory holding blupf90+: the 'blupf90_bin_dir' configuration key, else
# Breedbase's bin folder (where docker can mount the program), else the PATH.
# Returns undef when the site does not allow BLUPF90+ (allow_blupf90 0, the
# default) or blupf90+ is not installed.
sub blupf90_dir {
    my $c = shift;
    # the site must allow BLUPF90+ (free for research only; sgn.conf allow_blupf90)
    return if !$c->config->{allow_blupf90};
    my $conf = $c->config->{blupf90_bin_dir};
    return $conf if $conf && -x "$conf/blupf90+";
    # the program mounted into Breedbase's own bin folder (docker: a file bind
    # mount to <basepath>/bin/blupf90+; it is git-ignored)
    my $own = File::Spec->catdir($c->config->{basepath} // '', 'bin');
    return $own if -x "$own/blupf90+";
    foreach my $d (File::Spec->path()) {
        return $d if -x "$d/blupf90+";
    }
    return;
}

# Pedigree of the accessions with all their known ancestors (female_parent /
# male_parent stock relationships, followed recursively). Writes a
# tab-delimited file (Accession, Female_Parent, Male_Parent; the format of the
# Breedbase pedigree download) and returns summary counts.
# R packages installed for the R engine: glmmTMB (multi-trait repeated
# measurements) and AGHmatrix (pedigree / genomic / single-step relationship
# matrices); checked with Rscript, remembered for 10 minutes per process
my %R_PKG_CHECK;
sub r_package_available {
    my $pkg = shift;
    my $c = $R_PKG_CHECK{$pkg} ||= { at => 0, ok => 0 };
    if (time() - $c->{at} > 600) {
        my $ok = system('Rscript', '--vanilla', '-e', "quit(status = if (requireNamespace('$pkg', quietly = TRUE)) 0 else 1)") == 0 ? 1 : 0;
        %$c = (at => time(), ok => $ok);
    }
    return $c->{ok};
}
sub glmmtmb_available { return r_package_available('glmmTMB'); }
sub aghmatrix_available { return r_package_available('AGHmatrix'); }

